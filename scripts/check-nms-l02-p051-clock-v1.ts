import assert from 'node:assert/strict';
import {p051ClockInitial, p051ClockPlay, p051ClockPause, p051ClockSync, p051ClockEvent, p051ClockDuration, p051ClockMainFrame} from '../packages/demos/src/nms-l02-p051-clock-v1';
import {p051PhaseWindow, p051FrameSample, p051WindowOffset} from '../packages/demos/src/nms-l02-p051-audio-window-v1';
assert.equal(p051FrameSample(2), 1838); assert.equal(p051FrameSample(4), 5512);
assert.throws(() => p051FrameSample(0)); assert.throws(() => p051FrameSample(2.5));
let c = p051ClockPlay(p051ClockInitial(), 10);
c = p051ClockPause(c, 10.75); assert.equal(p051ClockMainFrame(c), 10);
assert.equal(p051ClockSync(c, 999), c);
c = p051ClockPlay(c, 1000); c = p051ClockSync(c, 2000);
assert.equal(c.state.phase, 'ready'); assert.equal(c.elapsed, 0); assert.equal(c.anchor, null);
assert.equal(p051ClockPlay(c, 2001), c);
c = p051ClockEvent(c, {type: 'drop', item: 1, target: null}, 2001);
const wrong = p051PhaseWindow(c.state)!;
assert.equal(wrong.start, 1838); assert.equal(wrong.domain, '248');
c = p051ClockPlay(c, 2002); c = p051ClockSync(c, 3000);
assert.equal(c.state.phase, 'wrong-feedback'); assert.equal(c.anchor, null);
assert.equal(p051ClockPlay(c, 3001), c);
c = p051ClockEvent(c, {type: 'close-wrong'}, 3001);
for (const item of [0, 2, 3, 5, 8]) {
  c = p051ClockEvent(c, {type: 'drop', item, target: item}, 4000);
  const window = p051PhaseWindow(c.state)!;
  assert.equal(window.end, 36562); assert.equal(window.domain, '250');
  assert.equal(p051WindowOffset(window, 9999), window.end);
  assert.throws(() => p051WindowOffset(window, -1));
  assert.throws(() => p051WindowOffset({...window, end: 999999}, 0));
  const token = c.state.token; c = p051ClockPlay(c, 4001);
  assert.equal(p051ClockSync(c, 4002, token - 1), c);
  const duration = p051ClockDuration(c);
  const almost = p051ClockSync(c, 4001 + duration - 0.001);
  assert.equal(almost.state.phase, 'correct-feedback');
  c = p051ClockSync(c, 5000);
  assert.equal(c.elapsed, 0); assert.equal(c.anchor, null);
}
assert.equal(c.state.phase, 'completion-feedback');
assert.equal(p051PhaseWindow(c.state), null); assert.equal(p051ClockDuration(c), 23 / 12);
c = p051ClockSync(p051ClockPlay(c, 6000), 7000);
assert.equal(c.state.phase, 'outro'); assert.equal(p051ClockMainFrame(c), 486);
assert.equal(p051PhaseWindow(c.state)!.start, p051FrameSample(485));
c = p051ClockSync(p051ClockPlay(c, 8000), 9000);
assert.equal(c.state.phase, 'complete'); assert.equal(p051ClockMainFrame(c), 503);
const replay = p051ClockEvent(c, {type: 'replay'}, 9001);
assert.equal(p051ClockMainFrame(replay), 1); assert.equal(replay.elapsed, 0);
assert.throws(() => p051ClockPlay(replay, NaN));
assert.throws(() => p051ClockSync(p051ClockPlay(replay, 10), 9));
console.log(JSON.stringify({status: 'PASS', checks: ['sample rounding', 'pause/resume', 'late callback isolation', 'wrong-popup wait', 'five correct tails', 'silent completion feedback', 'continuous main source resume', 'terminal503', 'Replay', 'invalid time/window rejection'], scope: 'Pure clock and phase windows; browser playback pending.'}));

#!/usr/bin/env node
/** Reversible local registration; all downstream acceptance remains closed. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {REGISTRY,DISPATCH,pinFile,readPin,readJsonPin,readRegistryTransaction,registrySources,
 readPageProof,verifyHostVersion,verifyAdmission,sha256} from '../lib/g678-admission-proof.mjs';
import {upsertPrivateCurrentJsCalibration} from './private-current-js-registry.mjs';
import {replacePinnedFile,rollbackPinnedFiles} from './register-nms-l02-p062-current-js-v1.mjs';
import * as S from '../lib/alg-l06-p003-admission-semantics-v1.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const DIR='output/alg-l06-p003-audio-alignment-20260928/formal-v1/registration-v2';
const ACTIVATION='apps/web/lib/g678-admission-activation.ts';
const INDEX='catalog/g678-admission-v1/index-v18.json';
const TARGETS=[REGISTRY,...DISPATCH,ACTIVATION];
const json=value=>Buffer.from(JSON.stringify(value,null,2)+'\n');
const pinBytes=(file,bytes)=>({path:file,bytes:bytes.length,sha256:sha256(bytes)});
const counts=registry=>{const entries=registry.calibrations.flatMap(row=>row.entries);
 return{total:entries.length,shared:entries.filter(row=>row.key.startsWith('shared-')).length,
  lesson:entries.filter(row=>row.key.startsWith('shared-alg001-l06-')).length};};
function local(){
 assert.equal(fs.realpathSync(ROOT),ROOT);assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT,S.SOURCE_ROOT);
 assert(!process.env.VERCEL&&!process.env.VERCEL_ENV&&process.env.NODE_ENV!=='production');
}
function descriptor(){
 const code=`import {algL6P003FormalDescriptor} from './apps/web/lib/alg-l06-p003-formal-admission-v1.server.ts';
 const d=algL6P003FormalDescriptor();if(d.pages.length!==60||d.productBridge.registeredAnimationCount!==20||
 d.pages[2].rendererAvailability.kind!=='registered'||Object.values(d.productBridge.acceptanceEffects).some(Boolean))
 throw Error('P003 formal descriptor');console.log(JSON.stringify({pages:60,registered:20,page:d.pages[2].animationId}));`;
 const result=spawnSync(process.execPath,['--conditions=react-server','--import','tsx','--input-type=module','-e',code],
  {cwd:ROOT,encoding:'utf8',timeout:120000,maxBuffer:1024*1024,env:{...process.env,NODE_ENV:'development',
   HELP_MATH_G678_LOCAL_PREVIEW:'1',HELP_MATH_G678_LOCAL_PREVIEW_BIND:'127.0.0.1'}});
 assert.equal(result.status,0,result.stderr||result.stdout||String(result.error));return JSON.parse(result.stdout.trim());
}
function plan(){
 local();S.readP003CanonicalSource(ROOT);
 const indexPin=pinFile(ROOT,INDEX),index=readJsonPin(ROOT,indexPin),host=verifyHostVersion(ROOT,index.host);
 assert.equal(index.host.path,'catalog/g678-admission-v1/host-v18.json');
 const proofRows=index.pages.filter(row=>row.animationId===S.ID);assert.equal(proofRows.length,1);
 const proof=readJsonPin(ROOT,proofRows[0].proof);
 S.validateP003AdmissionSemantics(proof.packet,proof.registration);
 const transaction=readRegistryTransaction(ROOT);
 assert.deepEqual(counts(transaction.registry),{total:638,shared:496,lesson:19});
 assert(!transaction.registry.calibrations.flatMap(row=>row.entries).some(row=>row.key===S.ID));
 const projected=upsertPrivateCurrentJsCalibration(transaction.registry,proof.registration);
 assert.deepEqual(counts(projected),{total:639,shared:497,lesson:20});
 for(const old of transaction.registry.calibrations)
  assert.deepEqual(projected.calibrations.find(row=>row.calibrationId===old.calibrationId),old);
 for(const row of index.pages)readPageProof(ROOT,row.proof,host,{...transaction,registry:projected});
 const before=TARGETS.map(file=>pinFile(ROOT,file));
 const currentActivation=readPin(ROOT,before[3]).toString();
 const activated=JSON.parse(currentActivation.slice(currentActivation.indexOf('=')+1,currentActivation.lastIndexOf(' as const;')));
 assert.deepEqual(activated,{path:'catalog/g678-admission-v1/index-v15.json',bytes:1864,
  sha256:'4b8b4552b502e94d7b66d53e94ddf82823ef44b6da8c6bb2b8588624bc341277'});
 const next=[json(projected),...registrySources(projected).map(text=>Buffer.from(text)),
  Buffer.from('// Reviewed split-proof activation. Generated by the admission build, not a page renderer.\nexport const G678_ADMISSION_INDEX = '+JSON.stringify(indexPin,null,2)+' as const;\n')];
 return{indexPin,proof:proofRows[0].proof,before,next,after:TARGETS.map((file,i)=>pinBytes(file,next[i])),projected};
}
function write(){
 const p=plan();assert(!fs.existsSync(path.join(ROOT,DIR)),'new transaction directory');fs.mkdirSync(path.join(ROOT,DIR),{recursive:true});
 const snapshots=p.before.map((pin,i)=>{
  const relative=`${DIR}/${i}-${path.basename(pin.path)}.before`;
  fs.writeFileSync(path.join(ROOT,relative),readPin(ROOT,pin),{flag:'wx'});return pinFile(ROOT,relative);});
 const intent={schemaVersion:1,animationId:S.ID,index:p.indexPin,proof:p.proof,before:p.before,after:p.after,snapshots,
  browserAndProductionValidation:'pending-formal-rerun',acceptanceEffects:S.ACCEPTANCE};
 fs.writeFileSync(path.join(ROOT,DIR,'intent.json'),json(intent),{flag:'wx'});
 const changed=[];
 try{
  assert.deepEqual(plan().after,p.after,'stable plan');
  for(let i=0;i<TARGETS.length;i++)replacePinnedFile(ROOT,TARGETS[i],p.before[i],p.next[i],()=>changed.push(i));
  assert.deepEqual(readRegistryTransaction(ROOT).registry,p.projected);
  verifyAdmission(ROOT,p.indexPin);const live=descriptor();
  const receipt={...intent,status:'registered-local-current-js-formal-browser-production-validation-pending',
   counts:{before:{total:638,shared:496,lesson:19},after:counts(p.projected)},descriptor:live};
  fs.writeFileSync(path.join(ROOT,DIR,'receipt.json'),json(receipt),{flag:'wx'});
  return receipt;
 }catch(error){
  const rollback=rollbackPinnedFiles(ROOT,changed.map(i=>({relative:TARGETS[i],after:p.after[i],beforeBytes:readPin(ROOT,snapshots[i])})));
  fs.writeFileSync(path.join(ROOT,DIR,'failure.json'),json({reason:String(error),rollback}),{flag:'wx'});throw error;
 }
}
function check(){
 local();const receipt=readJsonPin(ROOT,pinFile(ROOT,`${DIR}/receipt.json`));
 assert.deepEqual(receipt.acceptanceEffects,S.ACCEPTANCE);
 for(const pin of receipt.after)readPin(ROOT,pin);
 for(let i=0;i<TARGETS.length;i++)assert.deepEqual(pinBytes(TARGETS[i],readPin(ROOT,receipt.snapshots[i])),receipt.before[i]);
 verifyAdmission(ROOT,receipt.index);assert.deepEqual(counts(readRegistryTransaction(ROOT).registry),receipt.counts.after);
 assert.deepEqual(descriptor(),receipt.descriptor);return{status:'local-registration-checked',counts:receipt.counts,
  browserAndProductionValidation:'consult-separate-formal-evidence',acceptanceEffects:S.ACCEPTANCE};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert.equal(process.argv.length,3);const mode=process.argv[2];assert(['--plan','--write','--check'].includes(mode));
 const result=mode==='--write'?write():mode==='--check'?check():(()=>{const p=plan();return{
  status:'not-written',before:p.before,after:p.after,index:p.indexPin,proof:p.proof,acceptanceEffects:S.ACCEPTANCE};})();
 console.log(JSON.stringify(result));
}

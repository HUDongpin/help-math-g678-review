import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const source=fs.readFileSync('migrations/shared-nms002-l02-p049/audit/source-glossary-v1.json');
const decisions=fs.readFileSync('migrations/shared-nms002-l02-p049/audit/glossary-presentation-decisions-v1.json');
assert.equal(hash(source),'df7f31906aefdfe1baac09dd07e8644fdd99ce9b696fa9fb518b09c32db46627');
assert.equal(hash(decisions),'995959630301225000b1ba65e555d52b8e7bc90a7a431e2120d0ae1ed92676f7');
const correction=JSON.parse(decisions);assert.equal(correction.sourceGlossarySha256,hash(source));
const entries=JSON.parse(source).entries.map(({id,labels,definitions})=>{
 const corrected=correction.corrections.find(c=>c.id===id);
 return {id,labels,definitions:corrected?{en:corrected.en,es:corrected.es}:definitions};
});
assert.equal(entries.length,8);assert.deepEqual(correction.corrections.map(c=>c.id),['whole','power']);
const text='// Generated by scripts/generate-nms-l02-p049-glossary-v1.mjs; do not edit.\nexport const P049_GLOSSARY='+JSON.stringify(entries)+' as const;\n';
const output='packages/demos/src/generated/nms-l02-p049-glossary-v1.ts';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(output,'utf8'),text);else fs.writeFileSync(output,text);
console.log(JSON.stringify({status:'PASS',entries:8,explicitCorrections:['whole','power']}));

import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {prepareP052CandidatePcm} from './lib/nms-l02-p052-audio-plan-v1.mjs';
import {buildP052AudioWindows} from './lib/nms-l02-p052-audio-windows-v1.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'migrations/shared-nms002-l02-p052/audit');
const sha=b=>createHash('sha256').update(b).digest('hex');
const read=name=>JSON.parse(fs.readFileSync(path.join(dir,name)));
const source=read('source-identity-v1.json'),pcm=read('source-pcm-inventory-v1.json');
const planBytes=fs.readFileSync(path.join(dir,'native-audio-plan-v1.json'));
const plan=JSON.parse(planBytes),cues=read('native-audio-windows-v1.json');
const sourceSha='5efa48905e74c0dd604b9e896bee1a1b4cfb1fe0839044686527fe96e1311638';
assert.equal(source.source.sha256,sourceSha);
assert.equal(sha(fs.readFileSync(source.source.path)),sourceSha);
assert.equal(sha(fs.readFileSync(path.join(dir,'preserved-source-v1.swf'))),sourceSha);
for(const item of [pcm,plan,cues])assert.equal(item.sourceSha256,sourceSha);
assert.equal(sha(planBytes),cues.plan.sha256);
assert.equal(planBytes.length,cues.plan.bytes);
assert.equal(plan.implementationInputSha256,sha(fs.readFileSync(path.join(root,'scripts/lib/nms-l02-p052-audio-plan-v1.mjs'))));
assert.equal(cues.implementationSha256,sha(fs.readFileSync(path.join(root,'scripts/lib/nms-l02-p052-audio-windows-v1.mjs'))));
assert.deepEqual(cues.windows,buildP052AudioWindows(plan.plans));
assert.equal(pcm.streams.length,6);assert.equal(plan.plans.length,6);
const plans={};
for(const p of plan.plans){
 assert.ok(!Object.hasOwn(plans,p.domain));
 const matches=pcm.streams.filter(row=>row.domain===p.domain);assert.equal(matches.length,1);
 const row=matches[0];assert.equal(row.samples,p.decodedSamples);assert.equal(row.sampleRate,22050);assert.equal(row.channels,1);
 assert.deepEqual(row.pcm,p.input);
 for(const binding of [row.source,row.pcm]){
  assert.equal(binding.path,`migrations/shared-nms002-l02-p052/audit/${p.domain}-source-${binding===row.source?'stream-v1.mp3':'pcm-v1.f32le'}`);
  const b=fs.readFileSync(path.join(root,binding.path));assert.equal(b.length,binding.bytes);assert.equal(sha(b),binding.sha256);
 }
 const bytes=fs.readFileSync(path.join(root,row.pcm.path));
 const samples=Float32Array.from({length:bytes.length/4},(_,i)=>bytes.readFloatLE(i*4));
 prepareP052CandidatePcm(p,samples);
 plans[p.domain]={sampleRate:22050,channels:1,decodedSamples:p.decodedSamples,latencySamples:p.latencySamples,
  segments:p.segments,totalSamples:p.totalSamples,inputBytes:row.source.bytes,inputSha256:row.source.sha256,
  sourceSampleCountMismatch:p.sourceSampleCountMismatch,frame102ReplacementSamples:p.frame102ReplacementSamples};
}
const windows=Object.fromEntries(cues.windows.map(w=>[w.id,w]));
const output=path.join(root,'packages/demos/src/generated/nms-l02-p052-runtime-audio-v1.ts');
const text='// Generated by scripts/generate-nms-l02-p052-runtime-audio-v1.mjs; do not edit.\n'
 +`export const P052_AUDIO_SOURCE_SHA256=${JSON.stringify(sourceSha)};\n`
 +`export const P052_AUDIO_PLANS=${JSON.stringify(plans,null,2)} as const;\n`
 +`export const P052_AUDIO_WINDOWS=${JSON.stringify(windows,null,2)} as const;\n`;
if(fs.existsSync(output))assert.equal(fs.readFileSync(output,'utf8'),text);
else if(process.argv.includes('--check'))throw Error('Missing generated P052 audio');
else fs.writeFileSync(output,text,{flag:'wx'});
console.log(JSON.stringify({status:'PASS',domains:Object.keys(plans),windows:Object.keys(windows).length,audioAccepted:false}));

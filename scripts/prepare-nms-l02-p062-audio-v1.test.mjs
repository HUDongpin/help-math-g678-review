import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildP062AudioPlan,applyP062AudioPlan} from './prepare-nms-l02-p062-audio-v1.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source='/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';

test('P062 generator checks all full-EOF decodes and reproduces exact source binding',()=>{
 assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT,source);
 const plan=buildP062AudioPlan({root});
 const receipt=JSON.parse(plan.receipt.toString('utf8'));
 assert.equal(receipt.streams.length,11);
 assert.equal(receipt.feedbackTimings['sprite-85'].sourceTerminalFrame,70);
 assert.equal(receipt.feedbackTimings['sprite-85'].fullBufferWindowEndFrame,71);
 assert.equal(receipt.feedbackTimings['sprite-288'].decodedSamples,43776);
 assert.equal(receipt.streams.find(s=>s.ownerDomainId==='sprite-288').channels,2);
 assert.equal(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').decodedSamples,1503936);
 assert.deepEqual(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').emptyPayloadFrames,[10,828]);
 assert.deepEqual(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').negativeSeekBlocks,
  [{frame:828,seekSamples:-2239}]);
 assert.deepEqual(receipt.sourceMainStops,[384,523,650,766,815,834]);
 assert.equal(receipt.separateLessonSa.role,'index-only-not-spliced');
 assert.equal(receipt.policy.originalRuntimeSynchronizationEstablished,false);
 assert.equal(receipt.policy.listeningAccepted,false);
 assert.equal(applyP062AudioPlan(plan,'--check').status,'P062_AUDIO_CHECKED');
});

test('P062 producer rejects a wrong source root, decode drift, or generated byte change',()=>{
 const previous=process.env.HELP_MATH_G678_SOURCE_ROOT;
 try{process.env.HELP_MATH_G678_SOURCE_ROOT='/tmp/not-real-aws';
  assert.throws(()=>buildP062AudioPlan({root}),/real AWS source root/u);
 }finally{if(previous===undefined)delete process.env.HELP_MATH_G678_SOURCE_ROOT;
  else process.env.HELP_MATH_G678_SOURCE_ROOT=previous;}
 assert.throws(()=>buildP062AudioPlan({root,decodeWith:()=>({samples:1,pcmSha256:'f'.repeat(64)})}),
  /full EOF/u);
 const plan=buildP062AudioPlan({root});
 const changed={...plan,generated:Buffer.from(plan.generated)};
 changed.generated[0]^=1;
 assert.throws(()=>applyP062AudioPlan(changed,'--check'),/exact generated file/u);
 const target=path.join(root,'packages/demos/src/generated/nms-l02-p062-audio-v1.ts');
 assert.equal(fs.readFileSync(target).equals(plan.generated),true,'source-generated bytes preserved');
});

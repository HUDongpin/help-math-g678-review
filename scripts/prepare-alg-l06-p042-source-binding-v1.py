#!/usr/bin/env python3
"""Generate the exact local P042 physical and maintained input pin table."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_ROOT = Path('/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware')
OUTPUT = ROOT / 'apps/web/lib/alg-l06-p042-source-binding-v1.ts'
PHYSICAL = {
    'swf': 'G6-G8-shared/ALG001/L6/TI/L6TI02.swf',
    'xml': 'G6-G8-shared/ALG001/L6/index.xml',
    'sa': 'G6-G8-shared/ALG001/L6/SA/L6TI02.mp3',
}
MAINTAINED = {
    'sourceAudit': 'migrations/shared-alg001-l06-p042/audit-v1/source-audit.json',
    'sourcePins': 'migrations/shared-alg001-l06-p042/behavior-v1/source-pins-v2.json',
    'behaviorIr': 'migrations/shared-alg001-l06-p042/behavior-v1/behavior-ir-source-corrected-v2.json',
    'nativeModel': 'migrations/shared-alg001-l06-p042/native-v1/native-model-v1.json',
    'clipPlan': 'migrations/shared-alg001-l06-p042/native-v1/clip-plan-v1.json',
    'canvasMetadata': 'migrations/shared-alg001-l06-p042/canvas-v1/canvas-metadata-v1.json',
    'canvasRenderer': 'migrations/shared-alg001-l06-p042/canvas-v1/canvas-renderer.js',
    'audioSchedule': 'migrations/shared-alg001-l06-p042/audio-source-v1/source-audio-schedule-v1.json',
    'clockIr': 'migrations/shared-alg001-l06-p042/audio-source-v1/frame-sample-clock-ir-v1.json',
    'measuredBindings': 'migrations/shared-alg001-l06-p042/audio-source-v1/measured-bindings-v1.ts',
}


def pin(base: Path, path: str) -> dict[str, object]:
    data = (base / path).read_bytes()
    return {'path': path, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def render() -> bytes:
    rows = {'physical': {name: pin(SOURCE_ROOT, path) for name, path in PHYSICAL.items()}}
    rows.update({name: pin(ROOT, path) for name, path in MAINTAINED.items()})
    return ('/** Generated by scripts/prepare-alg-l06-p042-source-binding-v1.py. */\n'
            'export const P042_SOURCE_BINDING = '
            + json.dumps(rows, ensure_ascii=False, indent=2) + ' as const;\n').encode('utf-8')


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.write == args.check:
        parser.error('choose exactly one of --write or --check')
    desired = render()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        with OUTPUT.open('xb') as file:
            file.write(desired)
    elif OUTPUT.read_bytes() != desired:
        raise RuntimeError('P042 source binding drift')
    print(json.dumps({'path': str(OUTPUT.relative_to(ROOT)), 'bytes': len(desired),
                      'sha256': hashlib.sha256(desired).hexdigest()}))


if __name__ == '__main__':
    main()

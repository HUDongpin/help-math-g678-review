import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pin=(file,hash)=>{const b=readFileSync(path.join(root,file));assert.equal(createHash('sha256').update(b).digest('hex'),hash,file);return JSON.parse(b);};
export function buildAudioPlan(){
 const source=pin('migrations/shared-alg001-l06-p014/audit/audio-v1/audio-source-audit-v1.json','21430358709c5d2d5c3668774482a6981e34355605d50fbd2c5fa3c6e4bc63f8');
 const browser=pin('output/playwright/alg-l06-p014-browser-audio-v1/decode-receipt.json','e7489f077cbf3f9d55dfea53b15401b850af3803cd4c697682e83babd1c44f4a');
 const entries=[];
 for(const stream of source.streams){
  for(const [index,range] of stream.contiguousRanges.entries()){
   const mp3=range.extractedMp3??stream.extractedMp3;
   const decoded=range.decode??stream.decode;
   const measured=browser.results.find(r=>r.sourceSha256===mp3.sha256);
   assert(measured);assert.equal(measured.sourceBytes,mp3.bytes);
   assert.equal(measured.decodedSamples,decoded.samples);assert.equal(measured.playbackStarted,false);
   const id=stream.domain==='sprite-227'?`main-${index+1}`:stream.domain;
   entries.push({id,domain:stream.domain,firstBlockFrame:range.firstFrame,
    lastBlockFrame:range.lastFrame,lastVisualFrame:stream.domain==='sprite-227'?(index===0?120:449):stream.declaredFrames,
    initialSeekSamples:range.firstPacket.rawSeekSamples,
    sourcePath:mp3.path,sourceSha256:mp3.sha256,sourceBytes:mp3.bytes,
    sampleRate:measured.sampleRate,channels:measured.channels,decodedSamples:measured.decodedSamples,
    pcmSha256:measured.pcmSha256,
    receiptSha256:'e7489f077cbf3f9d55dfea53b15401b850af3803cd4c697682e83babd1c44f4a',
    originalRuntimeAccepted:false,audioAccepted:false});
  }
 }
 assert.equal(entries.length,9);
 const sa=browser.results.find(r=>r.role==='separate-sa');assert(sa);
 assert.equal(sa.sourceSha256,source.separateSa.copy.sha256);
 const output='// Generated by scripts/build-alg-l06-p014-audio-plan-v1.mjs; do not hand-edit.\n'+
  'export const P014_AUDIO_ASSETS='+JSON.stringify(entries,null,2)+' as const;\n'+
  'export const P014_SA_ASSET='+JSON.stringify({...sa,sourcePath:source.separateSa.copy.path,
   receiptSha256:'e7489f077cbf3f9d55dfea53b15401b850af3803cd4c697682e83babd1c44f4a',
   originalRuntimeAccepted:false,audioAccepted:false},null,2)+' as const;\n';
 return output;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const mode=process.argv[2];assert(['--write','--check'].includes(mode));
 const file=path.join(root,'packages/demos/src/generated/alg-l06-p014-audio-plan-v1.ts');
 const text=buildAudioPlan();
 if(mode==='--check')assert.equal(readFileSync(file,'utf8'),text);else writeFileSync(file,text);
 console.log(`${mode} P014 nine domain/range assets and separate SA; no playback acceptance`);
}

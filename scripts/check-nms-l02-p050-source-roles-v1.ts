import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {P050_TEXT_BINDING} from '../packages/demos/src/nms-l02-p050-text-snapshot-v1';
const root='migrations/shared-nms002-l02-p050/audit/';
const source=readFileSync(root+'source-input.swf');assert.equal(createHash('sha256').update(source).digest('hex'),P050_TEXT_BINDING.sourceSwfSha256);
const catalog=JSON.parse(readFileSync(root+'structural-intake-v1.json','utf8'));
const teaching=JSON.parse(readFileSync(root+'teaching-text-role-intake-v1.json','utf8'));
assert.equal(catalog.sourceSha256,P050_TEXT_BINDING.sourceSwfSha256);
assert.equal(teaching.sourceSha256,P050_TEXT_BINDING.sourceSwfSha256);
const used=[...new Set(P050_TEXT_BINDING.blocks.flatMap(b=>b.sourceTextIds.map(id=>Number(id.replace('character-','')))))].sort((a,b)=>a-b);
const expected=teaching.roles.map((r:{characterId:number})=>r.characterId).sort((a:number,b:number)=>a-b);
assert.deepEqual(used,expected);assert.equal(used.length,25);
assert.ok(used.every(id=>catalog.textDefinitions.some((d:{characterId:number})=>d.characterId===id)));
assert.ok(!used.some(id=>[55,90,92].includes(id)));
assert.deepEqual(P050_TEXT_BINDING.blocks.find(b=>b.id==='title')?.sourceShapeIds,[38]);
const report={sourceSha256:P050_TEXT_BINDING.sourceSwfSha256,nativeRoles:P050_TEXT_BINDING.blocks.length,teachingDefinitionsCovered:used,excludedOffstageDefinitions:[55,90,92],outlinedTitleShape:38,scope:'Semantic source associations; glossary bodies separately source-bound. Native accessibility additions are not verbatim Flash strings.',originalRuntimeAccepted:false};
if(process.argv.includes('--write'))writeFileSync(root+'native-text-role-coverage-v1.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({status:'PASS',nativeRoles:report.nativeRoles,teachingDefinitions:25}));

import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildP061AudioPlan,applyP061AudioPlan} from './prepare-nms-l02-p061-audio-v1.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source='/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';

test('P061 generator checks all full-EOF decodes and reproduces exact source binding',()=>{
 assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT,source);
 const plan=buildP061AudioPlan({root});
 const receipt=JSON.parse(plan.receipt.toString('utf8'));
 assert.equal(receipt.streams.length,11);
 assert.equal(receipt.feedbackTimings['sprite-87'].sourceTerminalFrame,70);
 assert.equal(receipt.feedbackTimings['sprite-87'].fullBufferWindowEndFrame,71);
 assert.equal(receipt.feedbackTimings['sprite-284'].decodedSamples,43776);
 assert.equal(receipt.streams.find(s=>s.ownerDomainId==='sprite-284').channels,2);
 assert.equal(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').decodedSamples,1590336);
 assert.deepEqual(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').emptyPayloadFrames,[10,875]);
 assert.deepEqual(receipt.streams.find(s=>s.ownerDomainId==='sprite-315').negativeSeekBlocks,
  [{frame:875,seekSamples:-2178}]);
 assert.deepEqual(receipt.sourceMainStops,[435,573,700,817,860,879]);
 assert.equal(receipt.separateLessonSa.role,'index-only-not-spliced');
 assert.equal(receipt.policy.originalRuntimeSynchronizationEstablished,false);
 assert.equal(receipt.policy.listeningAccepted,false);
 assert.equal(applyP061AudioPlan(plan,'--check').status,'P061_AUDIO_CHECKED');
});

test('P061 producer rejects a wrong source root, decode drift, or generated byte change',()=>{
 const previous=process.env.HELP_MATH_G678_SOURCE_ROOT;
 try{process.env.HELP_MATH_G678_SOURCE_ROOT='/tmp/not-real-aws';
  assert.throws(()=>buildP061AudioPlan({root}),/real AWS source root/u);
 }finally{if(previous===undefined)delete process.env.HELP_MATH_G678_SOURCE_ROOT;
  else process.env.HELP_MATH_G678_SOURCE_ROOT=previous;}
 assert.throws(()=>buildP061AudioPlan({root,decodeWith:()=>({samples:1,pcmSha256:'f'.repeat(64)})}),
  /full EOF/u);
 const plan=buildP061AudioPlan({root});
 const changed={...plan,generated:Buffer.from(plan.generated)};
 changed.generated[0]^=1;
 assert.throws(()=>applyP061AudioPlan(changed,'--check'),/exact generated file/u);
 const target=path.join(root,'packages/demos/src/generated/nms-l02-p061-audio-v1.ts');
 assert.equal(fs.readFileSync(target).equals(plan.generated),true,'source-generated bytes preserved');
});

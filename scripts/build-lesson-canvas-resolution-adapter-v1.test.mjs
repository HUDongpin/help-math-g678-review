import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import test from 'node:test';
import {mkdtemp, mkdir, readFile, writeFile, rm, symlink} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {buildLessonCanvasResolutionAdapter, buildLessonCanvasResolutionFromSpec} from './build-lesson-canvas-resolution-adapter-v1.mjs';

function source(width = 100, height = 75) {
  return `/* Generated by scripts/build-safe-ffdec-canvas-adapter.mjs. */
(function(global){'use strict';
var METADATA=Object.freeze({animationId:'test-lesson',sourceSwfSha256:'${'a'.repeat(64)}',stage:{width:${width},height:${height}}});
function render(targetCanvas,request){
 if(targetCanvas.width!==${width}||targetCanvas.height!==${height})throw new Error('native guard');
 var ctx=targetCanvas.getContext('2d');ctx.setTransform(1,0,0,1,0,0);ctx.fillRect(0,0,targetCanvas.width,targetCanvas.height);
 return {frame:request.frame,seed:request.seed};
}
var registry=global['HELP_MATH_CANVAS_ASSETS'];if(!registry){registry={};global['HELP_MATH_CANVAS_ASSETS']=registry;}
if(Object.prototype.hasOwnProperty.call(registry,'test-lesson'))throw new Error('duplicate');
registry['test-lesson']=Object.freeze({metadata:METADATA,render:render});
})(globalThis);`;
}
const hash = value => createHash('sha256').update(value).digest('hex');
function build(javascript = source()) {return buildLessonCanvasResolutionAdapter({javascript,expectedSha256:hash(javascript),variantId:'test-hd-v1'});}
function load(javascript, name = 'HELP_MATH_HD_CANVAS_ASSETS', key = 'test-hd-v1') {
  const context=vm.createContext({});vm.runInContext(javascript,context);return context[name][key];
}
function canvas(width,height){const calls=[];return{width,height,calls,getContext:()=>({setTransform:(...args)=>calls.push(['transform',...args]),fillRect:(...args)=>calls.push(['fill',...args])})};}

test('1x calls and teaching state stay identical and the new variant is independently registered',()=>{
  const original=source(),result=build(original),before=canvas(100,75),after=canvas(100,75);
  const old=load(original,'HELP_MATH_CANVAS_ASSETS','test-lesson'),next=load(result.javascript);
  assert.equal(JSON.stringify(old.render(before,{frame:14,seed:71})),JSON.stringify(next.render(after,{frame:14,seed:71})));
  assert.deepEqual(after.calls,before.calls);
  assert.deepEqual(JSON.parse(JSON.stringify(next.metadata.resolution)),{schemaVersion:1,mode:'adaptive-integer',nativeWidth:100,nativeHeight:75,supportedScales:[1,2]});
  assert.equal(next.metadata.animationId,'test-lesson');
  assert.equal(result.manifest.defaultEnabled,false);
});

test('2x changes only the root device transform and validates exact physical dimensions',()=>{
  const adapter=load(build().javascript),target=canvas(200,150);
  assert.equal(JSON.stringify(adapter.render(target,{frame:14,seed:71,renderScale:2})),JSON.stringify({frame:14,seed:71}));
  assert.deepEqual(target.calls,[['transform',2,0,0,2,0,0],['fill',0,0,100,75]]);
  assert.throws(()=>adapter.render(canvas(100,75),{renderScale:2}));
  assert.throws(()=>adapter.render(canvas(300,225),{renderScale:3}));
  assert.throws(()=>adapter.render(canvas(150,112),{renderScale:1.5}));
  assert.throws(()=>adapter.render(canvas(200,150),{renderScale:'2'}));
});

test('fractional authored dimensions remain fractional while backing dimensions round up',()=>{
  const adapter=load(build(source(100.25,75.05)).javascript),target=canvas(201,151);
  adapter.render(target,{frame:1,seed:0,renderScale:2});
  assert.equal(adapter.metadata.stage.width,100.25);
  assert.equal(adapter.metadata.resolution.nativeHeight,75.05);
  assert.deepEqual(target.calls,[['transform',2,0,0,2,0,0],['fill',0,0,100.5,75.5]]);
  assert.throws(()=>adapter.render(canvas(200,150),{renderScale:2}));
});

test('changed input, source transforms, unsupported envelopes and repeat transformation fail closed',()=>{
  const original=source();
  assert.throws(()=>buildLessonCanvasResolutionAdapter({javascript:original+' ',expectedSha256:hash(original),variantId:'test-hd-v1'}),/SHA/);
  assert.throws(()=>build(original.replace('ctx.setTransform(1,0,0,1,0,0)','ctx.setTransform(2,0,0,2,0,0)')),/root transform/);
  assert.throws(()=>build(original.replace('targetCanvas.width!==100','targetCanvas.width<100')),/backing guard/);
  assert.throws(()=>build(original+'\nsetTimeout(()=>{},1);'),/clock-bearing/);
  assert.throws(()=>build(build().javascript),/already transformed/);
});

test('the build is deterministic and its output hash binds the exact derived bytes',()=>{
  const first=build(),second=build();assert.deepEqual(first,second);
  assert.equal(hash(first.javascript),first.manifest.outputSha256);
  assert.equal(Buffer.byteLength(first.javascript),first.manifest.outputBytes);
});

test('an existing text variant keeps its original registry provenance when composed with HD',()=>{
  const input=source().replaceAll('HELP_MATH_CANVAS_ASSETS','HELP_MATH_TEXT_CANVAS_ASSETS')
    .replace('metadata:METADATA','metadata:Object.freeze(Object.assign({},METADATA,{textVariant:{variantRegistry:"HELP_MATH_TEXT_CANVAS_ASSETS"}}))');
  const adapter=load(build(input).javascript);
  assert.equal(adapter.metadata.textVariant.variantRegistry,'HELP_MATH_TEXT_CANVAS_ASSETS');
  assert.equal(adapter.metadata.resolutionVariant.originalRegistry,'HELP_MATH_TEXT_CANVAS_ASSETS');
});

test('the spec wrapper binds exact files, checks without rewriting, and refuses source or output substitution',async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'lesson-resolution-spec-'));
  t.after(()=>rm(root,{recursive:true,force:true}));
  const original=source(),spec={schemaVersion:1,kind:'lesson-canvas-resolution-spec-v1',
    input:{path:'source.js',sha256:hash(original)},variantId:'test-hd-v1',outputDirectory:'work/typography-v1/fixture'};
  await writeFile(path.join(root,'source.js'),original);await writeFile(path.join(root,'spec.json'),JSON.stringify(spec));
  const first=await buildLessonCanvasResolutionFromSpec('spec.json',{root});
  assert.deepEqual(await buildLessonCanvasResolutionFromSpec('spec.json',{root,check:true}),first);
  const generated=path.join(root,spec.outputDirectory,'canvas-renderer.js'),before=await readFile(generated);
  await writeFile(path.join(root,'source.js'),original+' ');
  await assert.rejects(buildLessonCanvasResolutionFromSpec('spec.json',{root}),/SHA/);
  assert.deepEqual(await readFile(generated),before);
  await writeFile(path.join(root,'source.js'),original);await writeFile(generated,'changed variant');
  await assert.rejects(buildLessonCanvasResolutionFromSpec('spec.json',{root,check:true}),/stale/);
  assert.equal(await readFile(generated,'utf8'),'changed variant');
  await symlink(os.tmpdir(),path.join(root,'outside'));
  await writeFile(path.join(root,'spec.json'),JSON.stringify({...spec,outputDirectory:'outside/new-output'}));
  await assert.rejects(buildLessonCanvasResolutionFromSpec('spec.json',{root}),/dedicated typography/);
  await assert.rejects(buildLessonCanvasResolutionFromSpec('../spec.json',{root}),/Unsafe/);
});

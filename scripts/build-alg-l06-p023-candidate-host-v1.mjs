#!/usr/bin/env node
/** Preserve the actual P022 My Lesson host and expose one P023 projection. */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';

const input=new URL('../apps/web/components/g678-alg-l06-p022-candidate-player-v1.generated.tsx',import.meta.url);
let source=fs.readFileSync(input,'utf8');
assert.equal(createHash('sha256').update(source).digest('hex'),
 '310afaaf9b3cc05efc504445ebb9705be0a032e63d65b88dfe8078f7c6d2c795');
for(const [from,to] of [
 ['G678AlgL6P022CandidatePlayer','G678AlgL6P023CandidatePlayer'],
 ['32 páginas registradas y 1 candidato sin registrar de ${descriptor.pages.length};',
  '33 páginas registradas y 1 candidato sin registrar de ${descriptor.pages.length};'],
 ['32 registered pages and 1 unregistered candidate of ${descriptor.pages.length};',
  '33 registered pages and 1 unregistered candidate of ${descriptor.pages.length};'],
 ['32/${descriptor.course.activePageCount} páginas registradas y 1 candidato sin registrar en My Lesson',
  '33/${descriptor.course.activePageCount} páginas registradas y 1 candidato sin registrar en My Lesson'],
 ['32/${descriptor.course.activePageCount} registered pages and 1 unregistered candidate in My Lesson',
  '33/${descriptor.course.activePageCount} registered pages and 1 unregistered candidate in My Lesson'],
]){
 assert.equal(source.split(from).length,2,`unique generated host phrase: ${from}`);
 source=source.replace(from,to);
}
source=source.replace(source.split('\n')[0],
 '// Generated by scripts/build-alg-l06-p023-candidate-host-v1.mjs; do not edit.');
const target=new URL('../apps/web/components/g678-alg-l06-p023-candidate-player-v1.generated.tsx',import.meta.url);
assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]),'--write|--check');
if(process.argv[2]==='--write')fs.writeFileSync(target,source);
else assert.equal(fs.readFileSync(target,'utf8'),source);
console.log('P023 candidate My Lesson player verified; 33 registered + 1 unregistered candidate');

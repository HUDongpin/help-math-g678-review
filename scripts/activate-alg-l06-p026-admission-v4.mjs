#!/usr/bin/env node
/** One-page local P026 admission. --plan is read-only; only --write mutates. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {ACCEPTANCE,ID,SOURCE_ROOT,validateP026Page}
 from '../lib/alg-l06-p026-admission-semantics-v1.mjs';
import {DISPATCH,REGISTRY,pinFile,readJsonPin,readOrdinary,readPageProof,
 readPin,readRegistryTransaction,registrySources,sha256,verifyAdmission,
 verifyHostVersion} from '../lib/g678-admission-proof.mjs';
import {upsertPrivateCurrentJsCalibration} from './private-current-js-registry.mjs';
import {guardedReplacement} from './activate-g678-frozen16-glossary-registration.mjs';

const ROOT=fs.realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'));
const CALIBRATION='g678-alg-l06-p026-current-js-20261001-v3';
const PROOF='work/g678-workflow/candidates/shared-alg001-l06-p026-proof-v3.json';
const PRIOR_REGISTRY_SHA='cb344e9b92499d5329c1ef3d6dfac1337e90ff4c139ece23aeab2a8d0a9cf7c3';
const PRIOR_INDEX={path:'catalog/g678-admission-v1/index-v91.json',bytes:6651,
 sha256:'3f35ecf1104a7bb886ffa10cbed820eb48812d3337d2b5109f4616ab1520410e'};
const PRIOR_HOST={path:'catalog/g678-admission-v1/host-v91.json',bytes:134459,
 sha256:'5c4818c72b54a3bc673f7dfe06a1affd555848fde54f77781d97c5c1e2b4ef95'};
const NEXT_INDEX='catalog/g678-admission-v1/index-v92.json';
const ACTIVATION='apps/web/lib/g678-admission-activation.ts';
const RECEIPT='output/alg-l06-p026-admission-activation-v4/recovery-v4.json';
const RECOVERY='work/g678-workflow/candidates/shared-alg001-l06-p026-activation-recovery-v4';
const TARGETS=[REGISTRY,...DISPATCH,ACTIVATION];
const serialize=value=>Buffer.from(JSON.stringify(value,null,2)+'\n');
const pin=(file,bytes)=>({path:file,bytes:bytes.length,sha256:sha256(bytes)});
const activation=pin=>Buffer.from('// Reviewed split-proof activation. Generated by the admission build, not a page renderer.\n'+
 `export const G678_ADMISSION_INDEX = ${JSON.stringify(pin,null,2)} as const;\n`);
const entries=registry=>registry.calibrations.flatMap(c=>c.entries);
const shared=registry=>entries(registry).filter(e=>e.key.startsWith('shared-'));

function exactPredecessor(){
 assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT,SOURCE_ROOT,
  'physical AWS source root must be explicit');
 assert.deepEqual(pinFile(ROOT,PRIOR_INDEX.path),PRIOR_INDEX,'exact predecessor index');
 assert.deepEqual(pinFile(ROOT,PRIOR_HOST.path),PRIOR_HOST,'exact predecessor host');
 const index=readJsonPin(ROOT,PRIOR_INDEX),host=verifyHostVersion(ROOT,index.host),
  transaction=readRegistryTransaction(ROOT);
 assert.deepEqual(index.host,PRIOR_HOST,'predecessor host association');
 assert.equal(index.pages.length,23,'exact 23 predecessor proofs');
 assert(!index.pages.some(p=>p.animationId===ID),'P026 absent from predecessor index');
 assert.equal(transaction.sha256,PRIOR_REGISTRY_SHA,'exact predecessor registry');
 assert.equal(transaction.registry.calibrations.length,136,'136 predecessor calibrations');
 assert.equal(entries(transaction.registry).length,655,'655 predecessor private entries');
 assert.equal(shared(transaction.registry).length,513,'513 predecessor shared entries');
 assert(!entries(transaction.registry).some(e=>e.key===ID),'P026 absent from registry');
 assert.deepEqual(readOrdinary(ROOT,ACTIVATION),activation(PRIOR_INDEX),
  'exact predecessor activation');
 for(const page of index.pages)readPageProof(ROOT,page.proof,host,transaction);
 return {index,host,transaction};
}

/** Build the exact successor entirely in memory before any target mutation. */
export function planActivation(){
 const base=exactPredecessor();
 assert(fs.existsSync(path.join(ROOT,PROOF)),'P026_V3_PROOF_NOT_PREPARED');
 const proofPin=pinFile(ROOT,PROOF),proof=readJsonPin(ROOT,proofPin);
 assert.equal(proof.animationId,ID,'one P026 proof identity');
 assert.equal(proof.registration.calibrationId,CALIBRATION,'exact v3 calibration');
 assert.deepEqual(proof.registration.entries.map(e=>e.key),[ID],
  'one P026 registration entry');
 const normalized=upsertPrivateCurrentJsCalibration(base.transaction.registry,
  proof.registration);
 const own=normalized.calibrations.find(c=>c.calibrationId===CALIBRATION);
 assert.deepEqual(own,proof.registration,'real writer produced exact own registration');
 // The writer sorts calibrations; retain the predecessor's actual order and
 // bytes of each entry so this transaction appends only the reviewed page.
 const byId=new Map(normalized.calibrations.map(c=>[c.calibrationId,c]));
 for(const old of base.transaction.registry.calibrations)
  assert.deepEqual(byId.get(old.calibrationId),old,'writer preserved '+old.calibrationId);
 const nextRegistry={...normalized,calibrations:[...base.transaction.registry.calibrations,own]};
 assert.deepEqual(nextRegistry.calibrations.filter(c=>c.calibrationId!==CALIBRATION),
  base.transaction.registry.calibrations,'all predecessor calibrations preserved');
 assert.equal(nextRegistry.calibrations.length,137,'one added calibration');
 assert.equal(entries(nextRegistry).length,656,'one added private entry');
 assert.equal(shared(nextRegistry).length,514,'one added shared entry');
 assert.deepEqual(shared(nextRegistry).filter(e=>e.key!==ID),shared(base.transaction.registry),
  'all predecessor shared entries preserved');
 const projected={registry:nextRegistry,sha256:sha256(serialize(nextRegistry))};
 const packet=readPageProof(ROOT,proofPin,base.host,projected);
 validateP026Page(packet,proof.registration,ROOT);
 assert.deepEqual(packet.acceptanceEffects,ACCEPTANCE,'separate acceptance gates');
 const successor={...base.index,pages:[...base.index.pages,{animationId:ID,proof:proofPin}]};
 assert.deepEqual(successor.pages.slice(0,-1),base.index.pages,
  'all predecessor proof pins and order preserved');
 assert.equal(successor.pages.length,24,'one additional proof');
 const indexBytes=serialize(successor),indexPin=pin(NEXT_INDEX,indexBytes);
 const registryBytes=serialize(nextRegistry),dispatch=registrySources(nextRegistry);
 const before=new Map(TARGETS.map(file=>[file,readOrdinary(ROOT,file)]));
 const after=new Map([[REGISTRY,registryBytes],
  ...DISPATCH.map((file,i)=>[file,Buffer.from(dispatch[i])]),
  [ACTIVATION,activation(indexPin)]]);
 assert.deepEqual([...before.keys()],[...after.keys()],'exact four replacement targets');
 return {base,proofPin,proof,packet,indexBytes,indexPin,nextRegistry,
  before,after,projected,
  summary:{beforeRegistry:pin(REGISTRY,before.get(REGISTRY)),
   afterRegistry:pin(REGISTRY,registryBytes),predecessorIndex:PRIOR_INDEX,
   successorIndex:indexPin,host:PRIOR_HOST,proof:proofPin,
   replacements:[...after].map(([file,bytes])=>pin(file,bytes)),
   preservedProofs:23,preservedCalibrations:136,preservedSharedEntries:513,
   registeredSharedEntries:514,publicFilesWritten:0,
   acceptanceEffects:ACCEPTANCE,productCalibrationPassed:false,
   scaleOutAuthorized:false,registered:false}};
}

function verifyInputs(plan){
 assert.deepEqual(pinFile(ROOT,PRIOR_INDEX.path),PRIOR_INDEX);
 assert.deepEqual(pinFile(ROOT,PRIOR_HOST.path),PRIOR_HOST);
 assert.deepEqual(pinFile(ROOT,PROOF),plan.proofPin,'unchanged real P026 proof');
 const host=verifyHostVersion(ROOT,PRIOR_HOST);
 for(const page of plan.base.index.pages)
  readPageProof(ROOT,page.proof,host,plan.base.transaction);
 const packet=readPageProof(ROOT,plan.proofPin,host,plan.projected);
 validateP026Page(packet,plan.proof.registration,ROOT);
 assert.deepEqual(packet.acceptanceEffects,ACCEPTANCE);
 assert.deepEqual(readPin(ROOT,plan.indexPin),plan.indexBytes,
  'immutable successor index');
}

function assertCurrentTargetBytes(states){
 for(const [file,bytes] of states)
  assert.deepEqual(readOrdinary(ROOT,file),bytes,`activation target drift: ${file}`);
}

function writeImmutableIndex(plan){
 const absolute=path.join(ROOT,NEXT_INDEX);
 if(fs.existsSync(absolute))assert.deepEqual(readPin(ROOT,plan.indexPin),plan.indexBytes,
  'existing immutable successor index');
 else fs.writeFileSync(absolute,plan.indexBytes,{flag:'wx'});
 assert.deepEqual(pinFile(ROOT,NEXT_INDEX),plan.indexPin);
}

export async function activate({mode='--plan'}={}){
 assert(['--plan','--write','--check'].includes(mode),'P026 activation mode');
 if(mode==='--check'){
  const receipt=readJsonPin(ROOT,pinFile(ROOT,RECEIPT));
  assert.deepEqual(receipt.acceptanceEffects,ACCEPTANCE);
  assert.equal(receipt.status,'local-registered-single-page-product-qa-pending');
  assert.deepEqual(receipt.predecessorIndex,PRIOR_INDEX);
  assert.deepEqual(receipt.host,PRIOR_HOST);
  assert.equal(receipt.proof.path,PROOF);
  const indexPin=pinFile(ROOT,NEXT_INDEX),admitted=verifyAdmission(ROOT,indexPin);
  assert.deepEqual(indexPin,receipt.successorIndex);
  assert.equal(admitted.index.pages.length,24);
  assert.deepEqual(admitted.index.pages.slice(0,-1),readJsonPin(ROOT,PRIOR_INDEX).pages);
  assert.deepEqual(admitted.index.pages.at(-1),{animationId:ID,proof:receipt.proof});
  const proof=readJsonPin(ROOT,receipt.proof);
  validateP026Page(admitted.packets[ID],proof.registration,ROOT);
  const current=readRegistryTransaction(ROOT).registry;
  assert.equal(current.calibrations.length,137);
  assert.equal(entries(current).length,656);
  assert.equal(shared(current).length,514);
  assert.deepEqual(pinFile(ROOT,REGISTRY),receipt.afterRegistry);
  for(const expected of receipt.replacements)assert.deepEqual(pinFile(ROOT,expected.path),expected);
  for(const backup of receipt.transaction.backups)readPin(ROOT,backup.backup);
  const registryBackup=receipt.transaction.backups.find(row=>row.target===REGISTRY);
  assert.deepEqual(registryBackup?.backup.sha256,PRIOR_REGISTRY_SHA,
   'exact predecessor registry retained in recovery');
  return {status:'checked-local-p026-admission',index:indexPin,
   registry:receipt.afterRegistry,registeredSharedEntries:514,
   acceptanceEffects:ACCEPTANCE};
 }
 const plan=planActivation();
 if(mode==='--plan')return {...plan.summary,status:'planned-not-written',
  registryWrites:0,indexWrites:0,activationWrites:0};
 assert(!fs.existsSync(path.join(ROOT,RECEIPT)),'P026 activation receipt already exists');
 assertCurrentTargetBytes(plan.before);
 writeImmutableIndex(plan);
 const verify=async()=>verifyInputs(plan);
 const postflight=async()=>{
  assertCurrentTargetBytes(plan.after);
  const admitted=verifyAdmission(ROOT,plan.indexPin);
  assert.equal(admitted.index.pages.length,24);
  assert.deepEqual(admitted.index.pages.at(-1),{animationId:ID,proof:plan.proofPin});
  validateP026Page(admitted.packets[ID],plan.proof.registration,ROOT);
  assert.equal(shared(readRegistryTransaction(ROOT).registry).length,514);
 };
 const transaction=await guardedReplacement({root:ROOT,before:plan.before,
  after:plan.after,targets:TARGETS,recovery:RECOVERY,verify,postflight});
 const receipt={schemaVersion:1,createdAt:new Date().toISOString(),
  status:'local-registered-single-page-product-qa-pending',...plan.summary,
  registered:true,transaction,activationTool:pinFile(ROOT,'scripts/activate-alg-l06-p026-admission-v4.mjs'),limitations:['Current-JS registry and local My Lesson route only; original runtime, audio listening, fidelity, human and Owner acceptance, strict completion and publication remain independent.']};
 await mkdir(path.dirname(path.join(ROOT,RECEIPT)),{recursive:true});
 await writeFile(path.join(ROOT,RECEIPT),serialize(receipt),{flag:'wx'});
 return {status:receipt.status,receipt:pinFile(ROOT,RECEIPT),
  registry:receipt.afterRegistry,index:receipt.successorIndex,
  registeredSharedEntries:514,acceptanceEffects:ACCEPTANCE};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--plan','--write','--check'].includes(process.argv[2]));
 console.log(JSON.stringify(await activate({mode:process.argv[2]}),null,2));
}

import {createHash} from 'node:crypto';
import {lstat, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = '/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';
const sourceRelative = 'G6-G8-shared/NMS002/L2/GS/L2GS03.swf';
const swfSha256 = '06bde171fe294f555f983c15b50afbb53344851cdc2f76e31e5eb5a4719cabb8';
const contractRelative = 'catalog/product-bridge-calibrations/g678-nms-l02-p053-p054-game-contract-v1.json';
const contractSha256 = '6d492f48cc2df39ca1636d5f9cde8f7529493eb3770c1d47c690a3c84b8aa205';
const layoutRelative = 'migrations/shared-nms002-l02-p054/audit/card-layout-v1.json';
const layoutSha256 = 'd34c6f2b89a99f110138c07b9b108ab96afa56db294a085a68a670d2cb034863';
const output = path.join(root, 'packages/demos/src/generated/nms-l02-p054-cards-v1.ts');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const requireFact = (condition, message) => {if (!condition) throw Error(message);};

async function pinnedJson(relativePath, expectedHash) {
  const bytes = await readFile(path.join(root, relativePath));
  requireFact(sha(bytes) === expectedHash, `${relativePath} drifted`);
  return JSON.parse(bytes);
}

async function main() {
  const mode = process.argv[2];
  requireFact(['--build', '--check'].includes(mode) && process.argv.length === 3,
    'use --build or --check');
  requireFact(process.env.HELP_MATH_G678_SOURCE_ROOT === sourceRoot, 'exact real source root required');
  const rootStat = await lstat(sourceRoot);
  requireFact(rootStat.isDirectory() && !rootStat.isSymbolicLink(),
    'Source must be a real directory, not symlink');
  const sourceBytes = await readFile(path.join(sourceRoot, sourceRelative));
  requireFact(sourceBytes.length === 2077270 && sha(sourceBytes) === swfSha256, 'P054 source drifted');
  const contract = await pinnedJson(contractRelative, contractSha256);
  const layout = await pinnedJson(layoutRelative, layoutSha256);
  requireFact(contract.source.p054.sha256 === swfSha256 && layout.source.swfSha256 === swfSha256,
    'P054 input source binding drifted');
  requireFact(contract.matching.cards.length === 24 && layout.cards.length === 24,
    'P054 card count drifted');
  const contractByKey = new Map(contract.matching.cards.map(card =>
    [`${card.level}:${card.sourceInstanceName}`, card]));
  const cards = layout.cards.map(row => {
    const source = contractByKey.get(`${row.level}:${row.sourceInstanceName}`);
    requireFact(source && source.sourceCharacterId === row.sourceCharacterId &&
      source.placementOrder === row.placementOrder &&
      source.pairId >= 1 && source.pairId <= 6 && [1, 2].includes(source.side),
    'P054 layout/card identity mismatch');
    const values = source.sourceTexts.map(text => text.value);
    requireFact(values.length === (source.side === 1 ? 2 : 1) &&
      values.every(value => typeof value === 'string' && value.length > 0),
    'P054 source card text mismatch');
    return {level: source.level, sourceFrame: row.sourceFrame,
      placementOrder: row.placementOrder, sourceInstanceName: source.sourceInstanceName,
      sourceCharacterId: source.sourceCharacterId, pairId: source.pairId, side: source.side,
      sourceTextIds: source.sourceTexts.map(text => text.id), values,
      stagePx: row.stagePx};
  });
  for (const level of [1, 2]) {
    const selected = cards.filter(card => card.level === level);
    requireFact(selected.length === 12 && new Set(selected.map(card => card.placementOrder)).size === 12 &&
      selected.every(card => card.sourceFrame === (level === 1 ? 2 : 4)),
    'P054 level board drifted');
  }
  const text = `// Generated by scripts/build-nms-l02-p054-card-data-v1.mjs; do not edit.\n`
    + `// Source-locked local candidate; not original-runtime or Current-JS acceptance.\n`
    + `export const P054_CARD_SOURCE = ${JSON.stringify({sourceSwfSha256: swfSha256,
      contractSha256, layoutSha256})} as const;\n`
    + `export const P054_CARDS = ${JSON.stringify(cards, null, 2)} as const;\n`;
  if (mode === '--check') requireFact(await readFile(output, 'utf8') === text,
    'P054 generated card data drifted');
  else await writeFile(output, text, {flag: 'wx'});
  console.log(JSON.stringify({status: 'PASS', mode, cards: cards.length, sha256: sha(text)}));
}

await main();

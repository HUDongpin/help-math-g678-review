#!/usr/bin/env node
/** Append-only candidate wrapper from the exact P060 generated host. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readPin,sha256} from '../lib/g678-admission-proof.mjs';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source={path:'apps/web/components/g678-nms-l02-p060-candidate-lesson-v1.generated.tsx',bytes:17260,
 sha256:'d5f81e52608eaa5ea8ae5ad2e42e3eaed77b18fbbf323f7305a6d4381923386f'};
const target='apps/web/components/g678-nms-l02-p061-candidate-lesson-v1.generated.tsx';
const previousHeader='// Generated by scripts/generate-nms-l02-p060-host-v1.mjs from the pinned P058 wrapper. Do not edit.';
const previousExport='export function G678NmsL02P060CandidateLessonV1';
const previousHost='data-p060-lesson-host>';
const previousIds=['p051','p052','p055','p056','p057','p058','p060'];
const replaceOnce=(text,from,to)=>{
 assert.equal(text.split(from).length,2,`single pinned wrapper marker: ${from}`);
 return text.replace(from,to);
};

export function buildP061Host(){
 let text=readPin(ROOT,source).toString();
 for(const id of previousIds){
  assert.equal((text.match(new RegExp(`animationId:'shared-nms002-l02-${id}'`,'gu'))??[]).length,1,
   `retained ${id} adapter`);
  assert(text.includes(`data-${id}-lesson-host`),`retained ${id} host marker`);
 }
 text=replaceOnce(text,previousHeader,
  '// Generated by scripts/generate-nms-l02-p061-host-v1.mjs from the pinned P060 wrapper. Do not edit.');
 text=replaceOnce(text,'const adapters = Object.freeze([',
  `const P061Solve = process.env.NODE_ENV === 'production' ? () => null
  : dynamic(() => import('./nms-l02-p061-lesson-runtime-v1').then(m => m.NmsL02P061LessonRuntimeV1), {ssr: false});
const adapters = Object.freeze([
 Object.freeze({animationId:'shared-nms002-l02-p061',audioEnabled:true,Component:P061Solve}),`);
 text=replaceOnce(text,previousExport,'export function G678NmsL02P061CandidateLessonV1');
 text=replaceOnce(text,previousHost,'data-p060-lesson-host data-p061-lesson-host>');
 assert.equal((text.match(/animationId:'shared-nms002-l02-p061'/gu)??[]).length,1);
 assert.equal((text.match(/data-p061-lesson-host/gu)??[]).length,1);
 return Buffer.from(text);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]),'use --write | --check');
 const bytes=buildP061Host(),file=path.join(ROOT,target);
 if(process.argv[2]==='--write')fs.writeFileSync(file,bytes,{flag:'wx'});
 else assert.deepEqual(fs.readFileSync(file),bytes,'P061 host reproducibility');
 console.log(JSON.stringify({status:'PASS',source,target,bytes:bytes.length,sha256:sha256(bytes)}));
}

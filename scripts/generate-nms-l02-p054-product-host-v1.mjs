#!/usr/bin/env node
/** Append only the P054 matching runtime adapter to the exact sealed P064 host. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readPin,sha256} from '../lib/g678-admission-proof.mjs';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source={path:'apps/web/components/g678-nms-l02-p064-candidate-lesson-v1.generated.tsx',bytes:18162,
 sha256:'ee673561ad12fcc1908385ffb41d2119299fd6ca40b957d1f25d5847fbfe9138'};
const target='apps/web/components/g678-nms-l02-p054-product-lesson-v1.generated.tsx';
const replaceOnce=(text,from,to)=>{
 assert.equal(text.split(from).length,2,`single pinned wrapper marker: ${from}`);
 return text.replace(from,to);
};

export function buildP054ProductHost(){
 let text=readPin(ROOT,source).toString();
 for(const id of ['p051','p052','p055','p056','p057','p058','p060','p061','p062','p064']){
  assert.equal((text.match(new RegExp(`animationId:'shared-nms002-l02-${id}'`,'gu'))??[]).length,1,
   `retained ${id} adapter`);
  assert(text.includes(`data-${id}-lesson-host`),`retained ${id} host marker`);
 }
 const previousAdapters=(text.match(/animationId:'shared-nms002-l02-p\d+'/gu)??[]).length;
 text=replaceOnce(text,
  '// Generated by scripts/generate-nms-l02-p064-host-v1.mjs from the pinned P062 wrapper. Do not edit.',
  '// Generated by scripts/generate-nms-l02-p054-product-host-v1.mjs from the pinned P064 wrapper. Do not edit.');
 text=replaceOnce(text,'const adapters = Object.freeze([',
  `const P054Matching = process.env.NODE_ENV === 'production' ? () => null
  : dynamic(() => import('./nms-l02-p054-lesson-runtime-v1').then(m => m.NmsL02P054LessonRuntimeV1), {ssr: false});
const adapters = Object.freeze([
 Object.freeze({animationId:'shared-nms002-l02-p054',audioEnabled:false,Component:P054Matching}),`);
 text=replaceOnce(text,'export function G678NmsL02P064CandidateLessonV1',
  'export function G678NmsL02P054ProductLessonV1');
 text=replaceOnce(text,'data-p064-lesson-host>',
  'data-p064-lesson-host data-p054-lesson-host>');
 assert.equal((text.match(/animationId:'shared-nms002-l02-p\d+'/gu)??[]).length,previousAdapters+1);
 assert.equal((text.match(/animationId:'shared-nms002-l02-p054'/gu)??[]).length,1);
 return Buffer.from(text);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]),'use --write | --check');
 const bytes=buildP054ProductHost(),file=path.join(ROOT,target);
 if(process.argv[2]==='--write')fs.writeFileSync(file,bytes,{flag:'wx'});
 else assert.deepEqual(fs.readFileSync(file),bytes,'P054 host reproducibility');
 console.log(JSON.stringify({status:'PASS',source,target,bytes:bytes.length,sha256:sha256(bytes)}));
}

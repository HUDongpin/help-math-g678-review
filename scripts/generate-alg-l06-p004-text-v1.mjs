#!/usr/bin/env node
/** Source-object text projection only; placement membership is not pixel visibility. */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readOrdinary} from '../lib/g678-admission-proof.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const AUDIT='migrations/shared-alg001-l06-p004/audit/source-text-v1.json';
const AUDIT_SHA='c6f15d46da49019e359a44f407cb0577f7cfb6a7a0c1b68ab06d43084aa3adc6';
const SWF_SHA='514867e794dbc86059a452c5f1091cabfabf73e6f7918d0d28d9cf7ee604573e';
const OUTPUT='packages/demos/src/alg-l06-p004-text.generated.ts';
export function generateP004Text(){
 const bytes=readOrdinary(ROOT,AUDIT);assert.equal(createHash('sha256').update(bytes).digest('hex'),AUDIT_SHA);
 const audit=JSON.parse(bytes);assert.equal(audit.sourceSha256,SWF_SHA);assert.equal(audit.summary.unresolvedRuns,0);
 const root=audit.timelines.find(t=>t.timelineId==='root'),main=audit.timelines.find(t=>t.timelineId==='sprite-95');
 assert.equal(main.declaredFrameCount,831);
 for(const id of [95,96])assert(root.instances.some(i=>i.characterId===id&&i.firstFrame===6&&i.lastFrameExclusive===11));
 const definitions=[audit.textDefinitions.find(d=>d.characterId===96),...audit.textDefinitions.filter(d=>main.instances.some(i=>i.characterId===d.characterId)).sort((a,b)=>a.sourceTagOffset-b.sourceTagOffset)];
 assert.equal(definitions.length,28,'all text definitions belong to root title or main sprite');
 const blocks=definitions.map(d=>{
  assert(d.runs.every((r,index)=>r.runIndex===index&&typeof r.text==='string'));
  const placements=d.characterId===96?[{firstFrame:1,lastFrameExclusive:832}]:main.instances.filter(i=>i.characterId===d.characterId);
  const active=new Set(placements.flatMap(i=>Array.from({length:i.lastFrameExclusive-i.firstFrame},(_,index)=>i.firstFrame+index)));
  const ranges=[];
  for(let frame=1;frame<=831;frame++)if(active.has(frame)){
   if(ranges.at(-1)?.[1]===frame-1)ranges.at(-1)[1]=frame;else ranges.push([frame,frame]);
  }
  return {characterId:d.characterId,sourceTextIds:d.runs.map(r=>r.sourceTextId),text:d.runs.map(r=>r.text).join(''),ranges};
 });
 const provenance={animationId:'shared-alg001-l06-p004',sourceSwfSha256:SWF_SHA,sourceAudit:{path:AUDIT,sha256:AUDIT_SHA},frameDomain:'sprite-95',frames:831,rootFrame:6,language:'en',
  ordering:'root title first, then text definitions by source tag offset; not inferred spatial reading order',
  joining:'join runs only within one DefineText object, preserving exact whitespace; never concatenate independent glyph objects',
  duplicatePolicy:'one block per character definition with merged placement intervals; runtime suppresses identical whole strings after selecting active blocks, retaining the first source-ordered match',
  visibilityBoundary:'source display-list membership only; alpha, masks, transformed off-stage positions and original-runtime pixel visibility are not asserted',
  translation:'none; English source strings remain English in Spanish UI',acceptanceEffect:'none'};
 return '// Generated by scripts/generate-alg-l06-p004-text-v1.mjs; do not edit.\n'+
  `export const P004_TEXT_PROVENANCE = ${JSON.stringify(provenance,null,2)} as const;\n`+
  `export const P004_SOURCE_TEXT_BLOCKS = ${JSON.stringify(blocks,null,2)} as const;\n`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--generate','--check'].includes(process.argv[2]),'usage: --generate|--check');
 const output=generateP004Text();
 if(process.argv[2]==='--check')assert.equal(readFileSync(path.join(ROOT,OUTPUT),'utf8'),output,'stale P004 text data');
 else writeFileSync(path.join(ROOT,OUTPUT),output);
 console.log(JSON.stringify({status:process.argv[2]==='--check'?'verified':'generated',path:OUTPUT,bytes:Buffer.byteLength(output),sha256:createHash('sha256').update(output).digest('hex')}));
}

"""Generate whole-stream preparation plans for the three source-invoked audio domains."""
from pathlib import Path
import json, hashlib, sys
R = Path(__file__).resolve().parents[1]
A = R / 'migrations/shared-nms002-l02-p051/audit'
anchors = json.loads((A / 'audio-sample-anchors-v1.json').read_text())
pcm = json.loads((A / 'source-pcm-inventory-v1.json').read_text())
assert anchors['sourceSha256'] == pcm['sourceSha256'] == '9c4c9857bb497497b4301a7b1cfec475b5f7bdf9d2cecabcd779fbd887de5d1f'
plans = {}
for domain in ['sprite-248', 'sprite-250', 'sprite-257']:
    row = next(x for x in anchors['rows'] if x['domain'] == domain)
    p = next(x for x in pcm['streams'] if x['domain'] == domain)
    assert p['sampleRate'] == 22050 and p['channels'] == 1
    for key in ['source', 'pcm']:
        b = (R / p[key]['path']).read_bytes()
        assert len(b) == p[key]['bytes'] and hashlib.sha256(b).hexdigest() == p[key]['sha256']
    cursor, end = 1673, 0
    for seg in row['segments']:
        assert seg['sourceStart'] == cursor < seg['sourceEnd'] <= p['samples']
        assert end <= seg['outputStart'] < seg['outputEnd']
        assert seg['sourceEnd'] - cursor == seg['outputEnd'] - seg['outputStart']
        cursor, end = seg['sourceEnd'], seg['outputEnd']
    assert cursor == p['samples'] and end == row['preparedSamples']
    plans[domain.split('-')[1]] = dict(sampleRate=22050, channels=1, decodedSamples=p['samples'],
        latencySamples=1673, totalSamples=end, segments=row['segments'],
        inputBytes=p['source']['bytes'], inputSha256=p['source']['sha256'])
text = '// Generated by scripts/generate-nms-l02-p051-audio-plan-v1.py; do not edit.\nexport const P051_AUDIO_PLANS=' + json.dumps(plans, separators=(',', ':')) + ' as const;\n'
output = R / 'packages/demos/src/generated/nms-l02-p051-audio-plan-v1.ts'
if '--check' in sys.argv:
    assert output.read_text() == text
else:
    output.write_text(text)
print(json.dumps({'status': 'PASS', 'selectedDomains': list(plans), 'unselectedPreservedDomains': ['177','189','217','228','252'], 'preparedSamples': {k: v['totalSamples'] for k, v in plans.items()}}))

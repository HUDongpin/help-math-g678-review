import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import {fileURLToPath, pathToFileURL} from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatorPath = path.join(projectRoot, "scripts/generate-nms-l02-p050-glossary-v1.mjs");
const sourcePath = path.join(
  projectRoot,
  "migrations/shared-nms002-l02-p050/audit/source-glossary-v1.json",
);
const decisionsPath = path.join(
  projectRoot,
  "migrations/shared-nms002-l02-p050/audit/glossary-presentation-decisions-v1.json",
);
const outputPath = path.join(
  projectRoot,
  "packages/demos/src/generated/nms-l02-p050-glossary-v1.ts",
);

const generator = await import(pathToFileURL(generatorPath).href);
const sourceBytes = fs.readFileSync(sourcePath);
const decisionsBytes = fs.readFileSync(decisionsPath);
const source = JSON.parse(sourceBytes.toString("utf8"));
const decisions = JSON.parse(decisionsBytes.toString("utf8"));

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function withTemp(callback) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "p050-glossary-"));
  try {
    return callback(root);
  } finally {
    fs.rmSync(root, {recursive: true, force: true});
  }
}

test("builds the six source-ordered entries and corrects only whole", () => {
  const built = generator.buildP050Glossary({sourceBytes, decisionsBytes});
  assert.deepEqual(built.glossary.map((entry) => entry.id), generator.ENTRY_IDS);
  assert.deepEqual(
    built.glossary.map((entry) => Object.keys(entry).sort()),
    Array.from({length: 6}, () => ["definitions", "id", "labels"]),
  );

  const byId = new Map(built.glossary.map((entry) => [entry.id, entry]));
  const sourceById = new Map(source.entries.map((entry) => [entry.id, entry]));
  for (const id of ["decimal", "fraction", "number-line", "part", "place-verb"]) {
    assert.deepEqual(byId.get(id).labels, sourceById.get(id).labels);
    assert.deepEqual(byId.get(id).definitions, sourceById.get(id).definitions);
  }

  assert.deepEqual(byId.get("whole").labels, {en: "Whole", es: "Todo"});
  assert.deepEqual(sourceById.get("whole").definitions, {
    en: "The total number of parts in a fraction.",
    es: "Número total de partes en una fracción.",
  });
  assert.deepEqual(byId.get("whole").definitions, {
    en: "The entire object, quantity, or group being considered. A fraction can represent part of that whole.",
    es: "El objeto, la cantidad o el grupo completo que se considera. Una fracción puede representar una parte de ese todo.",
  });
  assert.deepEqual(built.notation, {
    en: "This activity uses a decimal point, as in 0.8.",
    es: "En esta actividad usamos el punto decimal, como en 0.8.",
  });
  assert.equal(built.text.includes("2,68"), true);
  assert.equal(built.text.includes("0.8"), true);
});

test("rejects a mutated source or decision byte", () => {
  assert.throws(
    () => generator.buildP050Glossary({
      sourceBytes: Buffer.from(sourceBytes.toString("utf8").replace("Whole", "Wholes")),
      decisionsBytes,
    }),
    /source glossary bytes drifted/,
  );
  assert.throws(
    () => generator.buildP050Glossary({
      sourceBytes,
      decisionsBytes: Buffer.from(decisionsBytes.toString("utf8").replace("0.8", "0.9")),
    }),
    /presentation decision bytes drifted/,
  );
});

test("generated output exposes product fields only", () => {
  const text = fs.readFileSync(outputPath, "utf8");
  assert.match(text, /^\/\/ Generated by scripts\/generate-nms-l02-p050-glossary-v1\.mjs; do not edit\.\n/);
  assert.equal(text.includes("export const P050_GLOSSARY="), true);
  assert.equal(text.includes("export const P050_DECIMAL_NOTATION="), true);
  for (const forbidden of [
    "migrations/",
    "source-glossary",
    "glossary-presentation",
    "receipt",
    "/Volumes/",
    "HELP_KEYTERMS",
    "American Dream",
    "p050-pcode",
    "p050-scripts",
    source.entries[0].source.en.path,
  ]) {
    assert.equal(text.includes(forbidden), false, forbidden);
  }
  assert.equal(text.includes(source.entries.find((entry) => entry.id === "whole").definitions.en), false);
});

test("check compares bytes without writing and detects drift", () => {
  withTemp((root) => {
    const copySource = path.join(root, "source.json");
    const copyDecisions = path.join(root, "decisions.json");
    const copyOutput = path.join(root, "glossary.ts");
    fs.writeFileSync(copySource, sourceBytes);
    fs.writeFileSync(copyDecisions, decisionsBytes);
    const beforeSource = sha256(fs.readFileSync(copySource));
    const beforeDecisions = sha256(fs.readFileSync(copyDecisions));
    const rendered = generator.renderP050Glossary({
      sourcePath: copySource,
      decisionsPath: copyDecisions,
    });
    fs.writeFileSync(copyOutput, rendered.text);
    const beforeOutput = fs.readFileSync(copyOutput);
    const checked = generator.runCli(["--check"], {
      sourcePath: copySource,
      decisionsPath: copyDecisions,
      outputPath: copyOutput,
    });
    assert.equal(checked.status, "PASS");
    assert.deepEqual(fs.readFileSync(copyOutput), beforeOutput);
    assert.equal(sha256(fs.readFileSync(copySource)), beforeSource);
    assert.equal(sha256(fs.readFileSync(copyDecisions)), beforeDecisions);

    fs.writeFileSync(copyOutput, rendered.text.replace("0.8", "0,8"));
    assert.throws(
      () => generator.runCli(["--check"], {
        sourcePath: copySource,
        decisionsPath: copyDecisions,
        outputPath: copyOutput,
      }),
      /P050 glossary output drifted/,
    );
    assert.equal(fs.readFileSync(copyOutput, "utf8").includes("0,8"), true);
    assert.equal(sha256(fs.readFileSync(sourcePath)), generator.SOURCE_GLOSSARY_SHA256);
    assert.equal(sha256(fs.readFileSync(decisionsPath)), generator.DECISIONS_SHA256);
  });
});

test("write creates a missing file and refuses a different existing file", () => {
  withTemp((root) => {
    const copySource = path.join(root, "source.json");
    const copyDecisions = path.join(root, "decisions.json");
    const copyOutput = path.join(root, "nested", "glossary.ts");
    fs.writeFileSync(copySource, sourceBytes);
    fs.writeFileSync(copyDecisions, decisionsBytes);
    const created = generator.runCli(["--write"], {
      sourcePath: copySource,
      decisionsPath: copyDecisions,
      outputPath: copyOutput,
    });
    assert.equal(created.created, true);
    const first = fs.readFileSync(copyOutput);
    const unchanged = generator.runCli(["--write"], {
      sourcePath: copySource,
      decisionsPath: copyDecisions,
      outputPath: copyOutput,
    });
    assert.equal(unchanged.unchanged, true);
    assert.deepEqual(fs.readFileSync(copyOutput), first);

    fs.writeFileSync(copyOutput, Buffer.concat([first, Buffer.from("drift\n")]));
    const drifted = fs.readFileSync(copyOutput);
    assert.throws(
      () => generator.runCli(["--write"], {
        sourcePath: copySource,
        decisionsPath: copyDecisions,
        outputPath: copyOutput,
      }),
      /versioned successor/,
    );
    assert.deepEqual(fs.readFileSync(copyOutput), drifted);
  });
});

test("write preserves a file created after the existence check", () => {
  withTemp((root) => {
    const copyOutput = path.join(root, "glossary.ts");
    const existsSync = fs.existsSync;
    let injected = false;
    try {
      fs.existsSync = (candidate) => {
        if (candidate === copyOutput && !injected) {
          injected = true;
          fs.writeFileSync(copyOutput, "OTHER_WRITER_BYTES");
          return false;
        }
        return existsSync(candidate);
      };
      assert.throws(
        () => generator.runCli(["--write"], {outputPath: copyOutput}),
        {code: "EEXIST"},
      );
    } finally {
      fs.existsSync = existsSync;
    }
    assert.equal(injected, true);
    assert.equal(fs.readFileSync(copyOutput, "utf8"), "OTHER_WRITER_BYTES");
  });
});


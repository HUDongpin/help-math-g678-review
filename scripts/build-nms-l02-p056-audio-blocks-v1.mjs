#!/usr/bin/env node

import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {parseEmbeddedAudioPayloads} from './build-g4-l3-embedded-audio-archive.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = '/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';
const sourcePath = path.join(sourceRoot, 'G6-G8-shared/NMS002/L2/TS/L2TS03.swf');
const outputPath = path.join(projectRoot,
  'packages/demos/src/generated/nms-l02-p056-audio-blocks-v1.ts');
const sourceSha256 = 'a1872d6c20987340889c1077d6720cbfe046faa3b5228164987e0834f3c639be';
const payloadSha256 = '6ab63ac96194356d22da4335ce4ff121964044fc5dab27cc79b33fa22e2fc811';

const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

function readSource() {
  assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT, sourceRoot,
    'exact real G6–G8 source root required');
  const rootStat = fs.lstatSync(sourceRoot);
  assert.ok(rootStat.isDirectory() && !rootStat.isSymbolicLink(),
    'source root must be a real directory');
  const before = fs.lstatSync(sourcePath, {bigint: true});
  assert.ok(before.isFile() && !before.isSymbolicLink() && before.nlink === 1n);
  assert.equal(fs.realpathSync(sourcePath), sourcePath);
  const bytes = fs.readFileSync(sourcePath);
  const after = fs.lstatSync(sourcePath, {bigint: true});
  for (const key of ['dev', 'ino', 'size', 'mtimeNs', 'mode', 'nlink']) {
    assert.equal(after[key], before[key], `source changed during read: ${key}`);
  }
  assert.equal(sha256(bytes), sourceSha256);
  return bytes;
}

export function buildP056AudioBlocks() {
  const parsed = parseEmbeddedAudioPayloads(readSource());
  assert.deepEqual(parsed.tagCounts,
    {DefineSound: 0, SoundStreamHead: 1, SoundStreamHead2: 0, SoundStreamBlock: 230});
  assert.equal(parsed.soundStreams.length, 1);
  const stream = parsed.soundStreams[0];
  assert.equal(stream.ownerDomainId, 'sprite-24');
  assert.equal(stream.headLocalFrame, 1);
  assert.equal(stream.head.format, 'mp3');
  assert.equal(stream.head.sampleRateHz, 22050);
  assert.equal(stream.head.channels, 1);
  assert.equal(stream.head.mp3LatencySeek, 1673);
  assert.equal(stream.blockCount, 230);
  assert.equal(stream.totalBlockHeaderSampleCount, 422208);
  assert.equal(stream.payload.byteLength, 95290);
  assert.equal(stream.payload.sha256, payloadSha256);
  const counts = stream.blocks.map((block, index) => {
    assert.equal(block.localFrame, index + 5);
    const count = block.codecWrapperHeader.explicitSampleCount;
    assert.ok(Number.isInteger(count) && count >= 0);
    assert.equal(block.payload.byteLength * 576 / 130, count,
      `P056 MP3 payload/sample count drift at sprite frame ${block.localFrame}`);
    return count;
  });
  assert.equal(counts.reduce((sum, count) => sum + count, 0), 422208);
  return {
    source: {
      animationId: 'shared-nms002-l02-p056', sourceSwfSha256: sourceSha256,
      sourcePayloadSha256: payloadSha256, frameDomain: 'sprite-24',
      headFrame: 1, firstBlockFrame: 5, lastBlockFrame: 234,
      blockCount: 230, sampleRateHz: 22050, totalBlockHeaderSamples: 422208,
      mp3LatencySeekSamples: 1673,
    },
    counts,
  };
}

export function renderP056AudioBlocks({source, counts}) {
  return `// Generated by scripts/build-nms-l02-p056-audio-blocks-v1.mjs; do not edit.\n` +
    `// Source MP3 stream block accounting only; not audible, host-sync, or listening acceptance.\n` +
    `export const P056_AUDIO_BLOCK_SOURCE = ${JSON.stringify(source)} as const;\n` +
    `export const P056_AUDIO_BLOCK_SAMPLE_COUNTS: readonly number[] = ${JSON.stringify(counts)};\n`;
}

function main() {
  const mode = process.argv[2] ?? '--check';
  assert.ok(['--check', '--write'].includes(mode) && process.argv.length <= 3,
    'usage: node scripts/build-nms-l02-p056-audio-blocks-v1.mjs [--check|--write]');
  const bytes = Buffer.from(renderP056AudioBlocks(buildP056AudioBlocks()));
  if (mode === '--write') fs.writeFileSync(outputPath, bytes, {flag: 'wx'});
  else assert.ok(fs.readFileSync(outputPath).equals(bytes), 'P056 audio block IR drift');
  process.stdout.write(`${JSON.stringify({status: 'PASS', mode,
    output: path.relative(projectRoot, outputPath), bytes: bytes.length,
    sha256: sha256(bytes)})}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

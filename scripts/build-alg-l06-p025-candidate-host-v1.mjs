#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
const input=new URL('../apps/web/components/g678-alg-l06-p024-candidate-player-v1.generated.tsx',import.meta.url);
let source=fs.readFileSync(input,'utf8');
assert.equal(createHash('sha256').update(source).digest('hex'),'f50dc093a9efa2a14bb88205d079016ab84108c7461cf5b4e2fe23db93cd94df');
for(const [from,to] of [['G678AlgL6P024CandidatePlayer','G678AlgL6P025CandidatePlayer'],
 ['34 páginas registradas','35 páginas registradas'],['34 registered pages','35 registered pages'],
 ['34/${descriptor.course.activePageCount} páginas registradas','35/${descriptor.course.activePageCount} páginas registradas'],
 ['34/${descriptor.course.activePageCount} registered pages','35/${descriptor.course.activePageCount} registered pages']]){
 assert.equal(source.split(from).length,2);source=source.replace(from,to);
}
source=source.replace(source.split('\n')[0],'// Generated by scripts/build-alg-l06-p025-candidate-host-v1.mjs; do not edit.');
const file=new URL('../apps/web/components/g678-alg-l06-p025-candidate-player-v1.generated.tsx',import.meta.url);
assert(['--write','--check'].includes(process.argv[2]));
if(process.argv[2]==='--check'||fs.existsSync(file))assert.equal(fs.readFileSync(file,'utf8'),source);
else fs.writeFileSync(file,source,{flag:'wx'});
console.log('P025 candidate My Lesson player:35 registered+1 unregistered; source pinned');

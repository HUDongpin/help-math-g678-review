#!/usr/bin/env node
/** Append the P053 directions adapter to the exact registered P054 host. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readPin,sha256} from '../lib/g678-admission-proof.mjs';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source={path:'apps/web/components/g678-nms-l02-p054-product-lesson-v1.generated.tsx',bytes:18476,
 sha256:'9003bb9357ff728788ec3b2507df3bb0f183c86ac06175fa377ca7b1d9dd983f'};
const target='apps/web/components/g678-nms-l02-p053-product-lesson-v1.generated.tsx';
const replaceOnce=(text,from,to)=>{
 assert.equal(text.split(from).length,2,`single pinned wrapper marker: ${from}`);
 return text.replace(from,to);
};

export function buildP053ProductHost(){
 let text=readPin(ROOT,source).toString();
 for(const id of ['p051','p052','p055','p056','p057','p058','p060','p061','p062','p064','p054']){
  assert.equal((text.match(new RegExp(`animationId:'shared-nms002-l02-${id}'`,'gu'))??[]).length,1,
   `retained ${id} adapter`);
  assert(text.includes(`data-${id}-lesson-host`),`retained ${id} host marker`);
 }
 const previousAdapters=(text.match(/animationId:'shared-nms002-l02-p\d+'/gu)??[]).length;
 text=replaceOnce(text,
  '// Generated by scripts/generate-nms-l02-p054-product-host-v1.mjs from the pinned P064 wrapper. Do not edit.',
  '// Generated by scripts/generate-nms-l02-p053-product-host-v1.mjs from the pinned P054 wrapper. Do not edit.');
 text=replaceOnce(text,'const adapters = Object.freeze([',
  `const P053Directions = process.env.NODE_ENV === 'production' ? () => null
  : dynamic(() => import('./nms-l02-p053-lesson-runtime-v1').then(m => m.NmsL02P053LessonRuntimeV1), {ssr: false});
const adapters = Object.freeze([
 Object.freeze({animationId:'shared-nms002-l02-p053',audioEnabled:false,Component:P053Directions}),`);
 text=replaceOnce(text,'export function G678NmsL02P054ProductLessonV1',
  'export function G678NmsL02P053ProductLessonV1');
 text=replaceOnce(text,'data-p054-lesson-host>',
  'data-p054-lesson-host data-p053-lesson-host>');
 assert.equal((text.match(/animationId:'shared-nms002-l02-p\d+'/gu)??[]).length,previousAdapters+1);
 text=replaceOnce(text,"import('./nms-l02-p054-lesson-runtime-v1').then(m => m.NmsL02P054LessonRuntimeV1)",
  "import('./nms-l02-p053-game-handoff-runtime-v1').then(m => m.NmsL02P053GameHandoffRuntimeV1)");
 assert.equal((text.match(/animationId:'shared-nms002-l02-p053'/gu)??[]).length,1);
 return Buffer.from(text);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]),'use --write | --check');
 const bytes=buildP053ProductHost(),file=path.join(ROOT,target);
 if(process.argv[2]==='--write')fs.writeFileSync(file,bytes,{flag:'wx'});
 else assert.deepEqual(fs.readFileSync(file),bytes,'P053 host reproducibility');
 console.log(JSON.stringify({status:'PASS',source,target,bytes:bytes.length,sha256:sha256(bytes)}));
}

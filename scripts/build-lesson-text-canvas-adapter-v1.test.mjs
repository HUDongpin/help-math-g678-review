test("file builder writes a separate variant, verifies it and refuses changed-output overwrite", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "text-canvas-adapter-test-"));
  try {
    const options = fixture();
    const sourceBytes = Buffer.from(`${JSON.stringify(options.sourceAsset)}\n`);
    const compressed = gzipSync(sourceBytes, {mtime: 0});
    const assetPath = "catalog/typography-v1/source-catalog/assets/fixture.json.gz";
    const entry = {assetId: options.sourceAsset.assetId, sourceSha256: SOURCE_SHA,
      path: assetPath, artifactEncoding: "gzip-json", outputSha256: sha256(compressed),
      outputBytes: compressed.length, contentSha256: sha256(sourceBytes), contentBytes: sourceBytes.length};
    const bindingPath = "catalog/typography-v1/fixture-binding.json";
    const spec = {schemaVersion: 1, safeJavascript: {path: options.safeJavascriptPath,
      sha256: options.expectedSafeJavascriptSha256}, sourceAssetId: entry.assetId,
      binding: {path: bindingPath, sha256: options.bindingSha256}, variantId: options.variantId,
      output: {javascript: "work/typography-v1/fixture/variant.js", manifest: "work/typography-v1/fixture/manifest.json"}};
    const files = [[options.safeJavascriptPath, options.safeJavascript], [assetPath, compressed],
      ["catalog/typography-v1/source-catalog/index.json", JSON.stringify({assets: [entry]})],
      [bindingPath, options.bindingSerialized], ["spec.json", JSON.stringify(spec)]];
    for (const [relative, contents] of files) {
      await mkdir(path.dirname(path.join(root, relative)), {recursive: true});
      await writeFile(path.join(root, relative), contents);
    }
    const manifest = await buildLessonTextCanvasAdapterFromSpec("spec.json", {root});
    await buildLessonTextCanvasAdapterFromSpec("spec.json", {root, check: true});
    assert.equal(sha256(await readFile(path.join(root, options.safeJavascriptPath))), options.expectedSafeJavascriptSha256);
    assert.equal(sha256(await readFile(path.join(root, spec.output.javascript))), manifest.outputSha256);
    const changedBinding = `${JSON.stringify({...options.binding, version: "fixture-v2"})}\n`;
    await writeFile(path.join(root, bindingPath), changedBinding);
    await writeFile(path.join(root, "spec.json"), JSON.stringify({...spec,
      binding: {...spec.binding, sha256: sha256(changedBinding)}}));
    await assert.rejects(() => buildLessonTextCanvasAdapterFromSpec("spec.json", {root}), /refusing to overwrite/);
    assert.equal(sha256(await readFile(path.join(root, spec.output.javascript))), manifest.outputSha256);
  } finally {
    await rm(root, {recursive: true, force: true});
  }
});

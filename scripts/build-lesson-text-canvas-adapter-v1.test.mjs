test("generated variant is deterministic and does not add executable clocks or dynamic evaluation", () => {
  const options = fixture();
  const first = buildLessonTextCanvasAdapter(options);
  const second = buildLessonTextCanvasAdapter(options);
  assert.equal(first.code, second.code);
  assert.deepEqual(first.manifest, second.manifest);
  assert.equal(first.manifest.originalSafeJavascriptSha256, sha256(options.safeJavascript));
  assert.equal(first.manifest.outputSha256, sha256(first.code));
  assert.doesNotMatch(first.code, /\beval\s*\(|\bnew\s+Function\s*\(|\b(?:fetch|setTimeout|setInterval|requestAnimationFrame)\s*\(/);
});


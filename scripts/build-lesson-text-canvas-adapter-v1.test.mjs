function sourceTimeline(id, events, count = 3) {
  const instances = [];
  const generations = new Map();
  const active = new Map();
  events.forEach((event, index) => {
    event.eventId = `${id}/tag-${index}`;
    if (event.kind === "remove") {active.delete(event.depth); return;}
    if (event.characterId !== undefined) {
      const generation = (generations.get(event.depth) ?? 0) + 1;
      generations.set(event.depth, generation);
      const instance = {instanceId: `${id}/depth-${event.depth}/generation-${generation}`,
        depth: event.depth, generation, characterId: event.characterId};
      instances.push(instance);
      active.set(event.depth, instance);
    }
    event.instanceId = active.get(event.depth)?.instanceId;
  });
  return {timelineId: id, declaredFrameCount: count, instances, events};
}


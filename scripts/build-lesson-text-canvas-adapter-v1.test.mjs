function canvas() {
  const context = {matrix: I.slice(), stack: [], paints: [], globalAlpha: 1,
    save() {this.stack.push(this.matrix.slice());},
    restore() {this.matrix = this.stack.pop();},
    setTransform(...matrix) {this.matrix = matrix;},
    transform(a, b, c, d, e, f) {
      const x = this.matrix;
      this.matrix = [x[0] * a + x[2] * b, x[1] * a + x[3] * b,
        x[0] * c + x[2] * d, x[1] * c + x[3] * d,
        x[0] * e + x[2] * f + x[4], x[1] * e + x[3] * f + x[5]];
    },
    getTransform() {const [a,b,c,d,e,f] = this.matrix; return {a,b,c,d,e,f};},
    paint(id) {this.paints.push({id, matrix: this.matrix.slice()});},
  };
  return {width: 800, height: 600, context, getContext() {return context;}};
}

function load(options) {
  const result = buildLessonTextCanvasAdapter(options);
  const sandbox = {};
  new Script(options.safeJavascript).runInNewContext(sandbox);
  new Script(result.code).runInNewContext(sandbox);
  return {result, original: sandbox.HELP_MATH_CANVAS_ASSETS["course-fixture"],
    variant: sandbox.HELP_MATH_TEXT_CANVAS_ASSETS[options.variantId]};
}

test("same character and identical matrix at two depths suppresses only the bound instance", () => {
  const {variant, original, result} = load(fixture());
  const target = canvas();
  const observed = variant.renderWithText(target, {frame: 1, text: {suppressInstanceIds: ["bound-number"]}});
  assert.equal(target.context.paints.length, 1);
  assert.equal(observed.observations.length, 2);
  assert.equal(observed.observations[0].suppressed, true);
  assert.equal(observed.observations[1].depth, 2);
  assert.equal(observed.observations[1].suppressed, false);
  assert.deepEqual(Array.from(observed.observations[0].transform), MATRIX);
  assert.deepEqual(Array.from(observed.observations[0].colorRunsRgba[0]), [10,20,30,1]);
  assert.equal(original.metadata.animationId, "course-fixture");
  assert.equal(result.manifest.claimBoundary.pageEnabled, false);
  assert.equal(variant.metadata.textVariant.variantId, "course-fixture-text-v1");
});


test("remove, replacement and Replay retain deterministic source generation identity", () => {
  const {variant} = load(fixture());
  const request = frame => ({frame, text: {suppressInstanceIds: ["bound-number"]}});
  const first = variant.renderWithText(canvas(), request(1));
  const removed = variant.renderWithText(canvas(), request(2));
  const replaced = variant.renderWithText(canvas(), request(3));
  const replay = variant.renderWithText(canvas(), request(1));
  assert.equal(removed.observations.length, 1);
  assert.equal(removed.observations[0].depth, 2);
  assert.equal(replaced.observations[0].generation, 2);
  assert.equal(replaced.observations[0].suppressed, false);
  assert.equal(replay.observations[0].sourceInstanceId, first.observations[0].sourceInstanceId);
  assert.equal(replay.observations[0].suppressed, true);
});


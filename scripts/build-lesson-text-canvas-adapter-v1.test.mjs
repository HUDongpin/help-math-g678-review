test("input hash, source metadata, binding content and parent lineage are checked", () => {
  const base = fixture();
  assert.throws(() => buildLessonTextCanvasAdapter({...base, expectedSafeJavascriptSha256: "b".repeat(64)}), /SHA mismatch/);
  assert.throws(() => buildLessonTextCanvasAdapter({...base, sourceCatalogContentSha256: "b".repeat(64)}), /catalog content/);
  assert.throws(() => buildLessonTextCanvasAdapter({...base, bindingSha256: "b".repeat(64)}), /binding content/);
  const bad = structuredClone(base.binding); bad.blocks[0].instance.path[0].generation = 99;
  assert.throws(() => buildLessonTextCanvasAdapter(input(base.safeJavascript, base.sourceAsset, bad)), /missing from P1/);
  const changedMetadata = base.safeJavascript.replace(`sourceSwfSha256:"${SOURCE_SHA}"`,
    `sourceSwfSha256:"${"b".repeat(64)}"`);
  assert.throws(() => buildLessonTextCanvasAdapter(input(changedMetadata, base.sourceAsset, base.binding)),
    /metadata\/source catalog identity/);
});


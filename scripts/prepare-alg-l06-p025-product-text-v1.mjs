#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const INPUT='output/alg-l06-p025-native-text-v1/text-state-source-v1.json';
const SOURCE_SHA='a36a65777d4beb3b5d0db19a7c78dcdc40522eb44b6f856e932d8bf03f5ac83b';
const sha=body=>createHash('sha256').update(body).digest('hex');
export function build(){
 const body=fs.readFileSync(path.join(ROOT,INPUT));assert.equal(sha(body),SOURCE_SHA);
 const d=JSON.parse(body);assert.equal(d.animationId,'shared-alg001-l06-p025');
 const timeline={animationId:d.animationId,sourceSwfSha256:d.sourceSwfSha256,
  stage:{width:800,height:600},fps:12,rootEntryFrame:6,frameDomain:'sprite-21',mainFrameCount:299,
  nativeSourceSha256:SOURCE_SHA,glossaryInstances:d.glossaryControls.map(c=>({
   key:c.key,buttonId:c.buttonCharacterId,instanceId:c.buttonInstanceId,
   sourceActionSha256:c.sourceActionSha256,sourcePlacementTagSha256:c.sourcePlacementTagSha256,
   label:{textId:c.sourceLabelTextId,runText:c.sourceLabelRunText,segment:c.sourceLabelRunText,
    textInstanceId:c.sourceLabelInstanceId},
   availableSpans:c.sourceReadyIntervals.map(i=>[i.firstFrame,i.lastFrame])}))};
 const paragraphs=d.nativeGroups.map(g=>({name:g.name,sourceTextId:g.characterId,instanceId:g.instanceId,
  intervals:g.completeInkIntervals.map(i=>[i.firstFrame,i.lastFrame]),
  runs:d.textDefinitions.find(t=>t.characterId===g.characterId).runs}));
 assert.deepEqual(paragraphs.map(g=>[g.sourceTextId,g.intervals]),[[5,[[50,299]]],[15,[[295,299]]]]);
 for(const row of d.frames){
  const expected=paragraphs.filter(g=>g.intervals.some(([a,b])=>row.frame>=a&&row.frame<=b)).map(g=>g.sourceTextId);
  assert.deepEqual(expected,row.candidateSuppressibleSourceTextIds,'all active-instance suppression agrees');
 }
 const generated=`/* Generated by scripts/prepare-alg-l06-p025-product-text-v1.mjs; do not edit. */
export const P025_TIMELINE=${JSON.stringify(timeline,null,2)} as const;
export const P025_NATIVE_PARAGRAPHS=${JSON.stringify(paragraphs,null,2)} as const;
export type P025TimelineGlossaryKey=typeof P025_TIMELINE.glossaryInstances[number]['key'];
export function p025TimelineState(frame:number){
 if(!Number.isSafeInteger(frame)||frame<1||frame>299)throw new RangeError('P025_FRAME_OUT_OF_RANGE');
 const glossaryInstances=P025_TIMELINE.glossaryInstances.map(instance=>({...instance,
  available:instance.availableSpans.some(([a,b])=>frame>=a&&frame<=b)}));
 const nativeParagraphs=P025_NATIVE_PARAGRAPHS.filter(p=>p.intervals.some(([a,b])=>frame>=a&&frame<=b));
 return {frame,frameDomain:'sprite-21' as const,elapsedSeconds:(frame-1)/12,glossaryInstances,
  glossary:Object.fromEntries(glossaryInstances.map(g=>[g.key,g.available])),nativeParagraphs,
  suppressibleSourceTextIds:nativeParagraphs.map(p=>p.sourceTextId),
  originalRuntimeAccepted:false as const};
}
`;
 return [['packages/demos/src/alg-l06-p025-timeline-v1.ts',generated]];
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(['--write','--check'].includes(process.argv[2]));
 const outputs=build();for(const [name,body] of outputs){const file=path.join(ROOT,name);
  if(process.argv[2]==='--check'||fs.existsSync(file))assert.equal(fs.readFileSync(file,'utf8'),body);
  else fs.writeFileSync(file,body,{flag:'wx'});
 }console.log(JSON.stringify({status:process.argv[2],outputs:outputs.map(([name,body])=>({path:name,bytes:Buffer.byteLength(body),sha256:sha(body)}))}));
}

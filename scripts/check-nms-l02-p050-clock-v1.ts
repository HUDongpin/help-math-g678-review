import assert from 'node:assert/strict';
import {p050ClockInitial, p050ClockPlay, p050ClockPause, p050ClockSync, p050ClockEvent, p050ClockDuration, p050ClockMainFrame} from '../packages/demos/src/nms-l02-p050-clock-v1';
import {p050PhaseWindow, p050FrameSample, p050WindowOffset} from '../packages/demos/src/nms-l02-p050-audio-window-v1';
assert.equal(p050FrameSample(2), 1838); assert.equal(p050FrameSample(4), 5512);
assert.throws(() => p050FrameSample(0)); assert.throws(() => p050FrameSample(2.5));
let c = p050ClockPlay(p050ClockInitial(), 10);
c = p050ClockPause(c, 10.75); assert.equal(p050ClockMainFrame(c), 10);
assert.equal(p050ClockSync(c, 999), c);
c = p050ClockPlay(c, 1000); c = p050ClockSync(c, 2000);
assert.equal(c.state.phase, 'ready'); assert.equal(c.elapsed, 0); assert.equal(c.anchor, null);
assert.equal(p050ClockPlay(c, 2001), c);
c = p050ClockEvent(c, {type: 'drop', item: 1, target: null}, 2001);
const wrong = p050PhaseWindow(c.state)!;
assert.equal(wrong.start, 1838); assert.equal(wrong.domain, '88');
c = p050ClockPlay(c, 2002); c = p050ClockSync(c, 3000);
assert.equal(c.state.phase, 'wrong-feedback'); assert.equal(c.anchor, null);
assert.equal(p050ClockPlay(c, 3001), c);
c = p050ClockEvent(c, {type: 'close-wrong'}, 3001);
for (const item of [1, 2, 3, 4, 5]) {
  c = p050ClockEvent(c, {type: 'drop', item, target: item}, 4000);
  const window = p050PhaseWindow(c.state)!;
  assert.equal(window.end, 36562); assert.equal(window.domain, '91');
  assert.equal(p050WindowOffset(window, 9999), window.end);
  assert.throws(() => p050WindowOffset(window, -1));
  assert.throws(() => p050WindowOffset({...window, end: 999999}, 0));
  const token = c.state.token; c = p050ClockPlay(c, 4001);
  assert.equal(p050ClockSync(c, 4002, token - 1), c);
  const duration = p050ClockDuration(c);
  const almost = p050ClockSync(c, 4001 + duration - 0.001);
  assert.equal(almost.state.phase, 'correct-feedback');
  c = p050ClockSync(c, 5000);
  assert.equal(c.elapsed, 0); assert.equal(c.anchor, null);
}
assert.equal(c.state.phase, 'completion-feedback');
assert.equal(p050PhaseWindow(c.state), null); assert.equal(p050ClockDuration(c), 23 / 12);
c = p050ClockSync(p050ClockPlay(c, 6000), 7000);
assert.equal(c.state.phase, 'outro'); assert.equal(p050ClockMainFrame(c), 210);
assert.equal(p050PhaseWindow(c.state)!.start, p050FrameSample(209));
c = p050ClockSync(p050ClockPlay(c, 8000), 9000);
assert.equal(c.state.phase, 'complete'); assert.equal(p050ClockMainFrame(c), 260);
const replay = p050ClockEvent(c, {type: 'replay'}, 9001);
assert.equal(p050ClockMainFrame(replay), 1); assert.equal(replay.elapsed, 0);
assert.throws(() => p050ClockPlay(replay, NaN));
assert.throws(() => p050ClockSync(p050ClockPlay(replay, 10), 9));
console.log(JSON.stringify({status: 'PASS', checks: ['sample rounding', 'pause/resume', 'late callback isolation', 'wrong-popup wait', 'five correct tails', 'silent completion feedback', 'continuous main source resume', 'terminal260', 'Replay', 'invalid time/window rejection'], scope: 'Pure clock and phase windows; browser playback pending.'}));

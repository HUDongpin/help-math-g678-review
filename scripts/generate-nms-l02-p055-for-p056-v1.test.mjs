import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import test from 'node:test';
import {buildP055ForP056Files,generateP055ForP056} from './generate-nms-l02-p055-for-p056-v1.mjs';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');

test('four generated files reverse exactly to their frozen SHA-pinned P055 sources',async()=>{
  const files=await buildP055ForP056Files();
  assert.equal(files.length,4);
  assert.deepEqual(files.map(file=>file.replacements.length),[1,1,2,2]);
  for(const file of files){
    const source=await readFile(path.join(ROOT,file.source));
    const generated=await readFile(path.join(ROOT,file.output));
    assert.equal(sha(source),file.sourceSha256);
    assert.equal(sha(generated),file.sha256);
    assert.deepEqual(generated,file.bytes);
    let reversed=generated.toString('utf8');
    for(const {from,to} of [...file.replacements].reverse()){
      assert.equal(reversed.split(to).length,2,`only one occurrence in ${file.output}`);
      reversed=reversed.replace(to,from);
    }
    assert.deepEqual(Buffer.from(reversed,'utf8'),source,`unreviewed P055 delta: ${file.output}`);
  }
});

test('the successor chain retains P055 exports and changes only the two source-pinned asset URLs',async()=>{
  const files=await buildP055ForP056Files();
  const byOutput=new Map(files.map(file=>[path.basename(file.output),file.bytes.toString('utf8')]));
  const assets=byOutput.get('nms-l02-p055-for-p056-assets-v1.generated.ts');
  const renderer=byOutput.get('nms-l02-p055-for-p056-renderer-v1.generated.tsx');
  const module=byOutput.get('nms-l02-p055-for-p056-module-v1.generated.tsx');
  const runtime=byOutput.get('nms-l02-p055-for-p056-runtime-v1.generated.tsx');
  assert.match(assets,/export function loadP055NativeAsset/u);
  assert.match(renderer,/export function NmsL02P055NativeRenderer/u);
  assert.match(module,/export const nmsL02P055Module/u);
  assert.match(runtime,/export function NmsL02P055LessonRuntime/u);
  assert.match(assets,/\/migration-assets\/nms-l02-p056-predecessors\/p055-typography\.js\?sha256=47e796237e5520140a760175865f09c3f218ac942cf3cadc8fb9f56c38bd358d/u);
  assert.match(runtime,/\/migration-assets\/nms-l02-p056-predecessors\/p055-main\.mp3\?sha256=ca2a80e75f1fc25d4ff0696af4cc1ccfcec87a1518bbc88eda998b855865a20b/u);
  assert.doesNotMatch(files.map(file=>file.bytes.toString('utf8')).join('\n'),/\/migration-assets\/nms-l02-ts-pilot\//u);
  assert.match(renderer,/from '\.\/nms-l02-p055-for-p056-assets-v1\.generated'/u);
  assert.match(module,/from '\.\/nms-l02-p055-for-p056-renderer-v1\.generated'/u);
  assert.match(runtime,/import\('\.\.\/\.\.\/\.\.\/packages\/demos\/src\/nms-l02-p055-for-p056-module-v1\.generated'\)/u);
});

test('check mode revalidates source pins and generated bytes without writing',async()=>{
  const receipt=await generateP055ForP056('--check');
  assert.equal(receipt.files.length,4);
  assert.equal(receipt.acceptanceEffects.p055SourceChanged,false);
  assert.equal(receipt.acceptanceEffects.p056Registered,false);
});

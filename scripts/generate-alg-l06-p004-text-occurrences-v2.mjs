#!/usr/bin/env node
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readOrdinary} from '../lib/g678-admission-proof.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const INPUT='migrations/shared-alg001-l06-p004/audit/source-text-v1.json';
const OUTPUT='packages/demos/src/alg-l06-p004-text-occurrences-v2.generated.ts';
export function generateP004TextOccurrences(){
 const bytes=readOrdinary(ROOT,INPUT),hash=createHash('sha256').update(bytes).digest('hex');
 assert.equal(hash,'c6f15d46da49019e359a44f407cb0577f7cfb6a7a0c1b68ab06d43084aa3adc6');
 const source=JSON.parse(bytes);assert.equal(source.sourceSha256,'514867e794dbc86059a452c5f1091cabfabf73e6f7918d0d28d9cf7ee604573e');
 const definitions=new Map(source.textDefinitions.map(d=>[d.characterId,d]));
 const main=source.timelines.find(t=>t.timelineId==='sprite-95'),root=source.timelines.find(t=>t.timelineId==='root');
 const parent=root.instances.find(i=>i.characterId===95&&i.firstFrame===6);
 assert(parent&&main.declaredFrameCount===831);
 const parentEvent=root.events.find(e=>e.eventId===parent.createdByEventId);
 assert.deepEqual(parentEvent.matrix,[1,0,0,1,7390,5060]);
 const rows=[];
 for(const timeline of [root,main])for(const instance of timeline.instances){
  const definition=definitions.get(instance.characterId);
  if(!definition||(timeline===root&&instance.characterId!==96))continue;
  const events=instance.updates.map(id=>{const event=timeline.events.find(e=>e.eventId===id);assert(event);return event;});
  rows.push({instanceId:instance.instanceId,instancePath:timeline===root?instance.instanceId:`${parent.instanceId}/${instance.instanceId}`,
   timelineId:timeline.timelineId,characterId:instance.characterId,depth:instance.depth,generation:instance.generation,
   sourceTextId:definition.sourceTextId,sourceTextIds:definition.runs.map(r=>r.sourceTextId),
   text:definition.runs.map(r=>r.text).join(''),runs:definition.runs.map(({glyphs,...run})=>run),
   firstFrame:timeline===root?1:instance.firstFrame,lastFrameExclusive:timeline===root?832:instance.lastFrameExclusive,
   sourceFirstFrame:instance.firstFrame,sourceLastFrameExclusive:instance.lastFrameExclusive,
   boundsTwips:definition.boundsTwips,textMatrix:definition.matrix,placementEvents:events,
   parentMatrix:timeline===root?[1,0,0,1,0,0]:parentEvent.matrix,
   revealPolicy:'membership-only-unresolved-alpha-mask-offstage',geometryUnits:'source-twips'});
 }
 rows.sort((a,b)=>(a.timelineId==='root'?-1:0)-(b.timelineId==='root'?-1:0)||a.firstFrame-b.firstFrame||a.depth-b.depth||a.generation-b.generation);
 const equation=rows.filter(r=>r.timelineId==='sprite-95'&&r.firstFrame<=93&&r.lastFrameExclusive>93&&[52,39].includes(r.characterId));
 assert.deepEqual(equation.map(r=>r.characterId),[52,39]);
 const provenance={sourceAudit:{path:INPUT,sha256:hash},sourceSwfSha256:source.sourceSha256,frameDomain:'sprite-95',frameCount:831,rootFrame:6,
  ordering:'root title first; then instance creation frame, depth, generation; not claimed semantic reading order',
  duplicates:'all source instances retained; no string deduplication',
  transforms:'source text matrix/bounds, parent placement matrix and complete ordered placement update events; no alpha or mask visibility inference',
  equation93:{status:'unknown-semantic-composition',instanceIds:equation.map(r=>r.instanceId),sourceStrings:equation.map(r=>r.text),
   decision:'two co-present source objects with recorded geometry; kept separate until operator role and semantic placement are independently reviewed'},
  title:'character-96 held at root frame6; sprite98 is not title text',acceptanceEffect:'none'};
 return '// Generated by scripts/generate-alg-l06-p004-text-occurrences-v2.mjs; do not edit.\n'+
  `export const P004_TEXT_OCCURRENCE_PROVENANCE = ${JSON.stringify(provenance,null,2)} as const;\n`+
  `export const P004_TEXT_OCCURRENCES = ${JSON.stringify(rows,null,2)} as const;\n`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--generate','--check'].includes(process.argv[2]));const result=generateP004TextOccurrences();
 if(process.argv[2]==='--check')assert.equal(readFileSync(path.join(ROOT,OUTPUT),'utf8'),result);
 else writeFileSync(path.join(ROOT,OUTPUT),result);
 console.log(JSON.stringify({path:OUTPUT,bytes:Buffer.byteLength(result),sha256:createHash('sha256').update(result).digest('hex')}));
}

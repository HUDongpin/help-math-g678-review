"""Generate compact native presentation data from hash-bound P039 source audits."""
import argparse, hashlib, json, pathlib, re
parser = argparse.ArgumentParser()
parser.add_argument('--audit-root', type=pathlib.Path, required=True)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
expected = {
 'source-intro-grid-audit-v2.json': 'c3d74e9dfb7363f86c9f62da066d47cf95aa5def8a774c69ccc7fab638dd015e',
 'source-glyph-mask-schedule-v2.json': '210ebe2adfd6c5969c1fe362b0c8add8d16aa6ba75d101a63aa8bf20dde23b13',
}
data = {}
for name, digest in expected.items():
 raw = (args.audit_root / name).read_bytes()
 if hashlib.sha256(raw).hexdigest() != digest:
  raise ValueError('P039 audit hash mismatch: ' + name)
 data[name] = json.loads(raw)
audit = data['source-intro-grid-audit-v2.json']
rows = audit['rows']
assert audit['status'] == 'PASS' and [r['frame'] for r in rows] == list(range(1, 546))
# Run-length encode complete source poses; keep cell identities, not just counts.
beats = []
for row in rows:
 pose = {k: row[k] for k in ['sourceFillId', 'gridAlpha', 'sourceHandleX', 'pointer', 'emphasisIds', 'filled', 'outlined']}
 for key in ['filled', 'outlined']:
  assert len(set(pose[key])) == len(pose[key]) and all(0 <= c < 100 for c in pose[key])
 if not beats or pose != beats[-1]['pose']:
  beats.append({'firstFrame': row['frame'], 'lastFrame': row['frame'], 'pose': pose})
 else:
  beats[-1]['lastFrame'] = row['frame']
for row in rows:
 beat = next(b for b in beats if b['firstFrame'] <= row['frame'] <= b['lastFrame'])
 assert all(beat['pose'][k] == row[k] for k in beat['pose'])
glyph_audit = data['source-glyph-mask-schedule-v2.json']
sentences = []
for low, high, text in [
 (14, 70, 'Use your mouse to click and drag the slider to shade 25 percent of this grid.'),
 (74, 112, 'When you have finished, click the Done button.'),
]:
 glyphs = [g for g in glyph_audit['glyphSchedule'] if low <= int(re.search(r'/depth-(\d+)', g['id'])[1]) <= high]
 glyphs.sort(key=lambda g: (-int(re.search(r'/depth-(\d+)', g['id'])[1]), int(re.search(r'/glyph-(\d+)', g['id'])[1])))
 assert ''.join(g['text'] for g in glyphs) == text.replace(' ', '')
 # Whitespace is a native sentence-layout decision; each nonspace glyph remains source-bound.
 cursor = 0
 schedule = []
 for offset, char in enumerate(text):
  if char == ' ':
   continue
  glyph = glyphs[cursor]
  assert glyph['text'] == char and glyph['firstFullContainment'] is not None
  schedule.append({'offset': offset, 'id': glyph['id'], 'firstFrame': glyph['firstFullContainment']})
  cursor += 1
 # A first-visible schedule is valid only if source containment stays monotonic in this domain.
 for frame in glyph_audit['frames'][:545]:
  statuses = {g['id']: g['status'] for t in frame['texts'] for g in t['glyphs']}
  for g in schedule:
   assert (statuses.get(g['id']) == 'fully-contained') == (frame['frame'] >= g['firstFrame']), (frame['frame'], g)
 sentences.append({'text': text, 'glyphs': schedule})
assert all(g['firstFullContainment'] is None for g in glyph_audit['glyphSchedule'] if '/depth-71/' in g['id'])
output = {'animationId': 'shared-nms002-l02-p039', 'sourceSha256': 'cb087b675e4ada79fb53d4a7f7368f69ed96abf6a71ea4c6e56afdaa683bd649',
 'auditSha256': expected, 'firstFrame': 1, 'lastFrame': 545, 'beats': beats, 'sentences': sentences,
 'qualification': 'Source geometry audit; conservative fully-contained glyph timing; native whitespace; no original-runtime acceptance.'}
serialized = '// Generated by scripts/generate-nms-l02-p039-intro-v1.py. Do not edit.\nexport const P039_INTRO_SOURCE = ' + json.dumps(output, separators=(',', ':')) + ' as const;\n'
serialized += "function freeze<T>(value:T):T { if(value && typeof value==='object' && !Object.isFrozen(value)){Object.freeze(value); for(const child of Object.values(value))freeze(child);} return value;}\nfreeze(P039_INTRO_SOURCE);\n"
path = root / 'packages/demos/src/generated/nms-l02-p039-intro-source-v1.ts'
if args.check:
 assert path.read_text() == serialized, 'P039 generated intro drift'
else:
 path.write_text(serialized)
print(json.dumps({'status': 'PASS', 'check': args.check, 'frames': len(rows), 'beats': len(beats), 'glyphs': sum(len(s['glyphs']) for s in sentences), 'sha256': hashlib.sha256(serialized.encode()).hexdigest()}))

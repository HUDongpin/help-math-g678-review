/** Root-reviewed one-page P028 local admission with exact guarded recovery. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DISPATCH,REGISTRY,pinFile,readJsonPin,readOrdinary,readPageProof,
 readPin,readRegistryTransaction,registrySources,sha256,verifyAdmission,
 verifyHostVersion} from '../lib/g678-admission-proof.mjs';
import {upsertPrivateCurrentJsCalibration} from './private-current-js-registry.mjs';
import {guardedReplacement} from './activate-g678-frozen16-glossary-registration.mjs';

const ROOT=fs.realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'));
const ID='shared-alg001-l06-p028';
const SOURCE_ROOT='/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';
const SOURCE={path:'G6-G8-shared/ALG001/L6/VB/L6VB21.swf',bytes:47191,
 sha256:'12b9912231512d5622b96708b83331217691169fadf185b3b2d0a27733e3c297'};
const SOURCE_XML={path:'G6-G8-shared/ALG001/L6/index.xml',bytes:13926,
 sha256:'9f3753a17e5e271d7bc63a1bdf8cd5237f19770bae3f5c7364cabcb62c84ce2c'};
const SOURCE_SA={path:'G6-G8-shared/ALG001/L6/SA/L6VB21.mp3',bytes:37632,
 sha256:'f056221dc3c4251538c3a1d2c201bec5abe92c18a58f6ce1d185a8a6cf6703cf'};
const ACCEPTANCE={authoritativeOriginalRuntime:false,fidelityAccepted:false,
 audioAccepted:false,listeningAccepted:false,humanVisualAccepted:false,
 ownerAccepted:false,strictComplete:false,published:false};
const CALIBRATION='g678-alg-l06-p028-current-js-20261001-v3';
const PROOF='work/g678-workflow/candidates/shared-alg001-l06-p028-proof-v3.json';
const PRIOR_REGISTRY_SHA='d1d56ce92fe29a25c072f93cdf6b0aa2ce97a40c455f13af261d88fe16b99d65';
const PRIOR_INDEX={path:'catalog/g678-admission-v1/index-v95.json',bytes:7213,
 sha256:'abc289363ad1de972e53bc4eeed881db05ab82fb1c59c9aed56a4dedcf4acb69'};
const PRIOR_HOST={path:'catalog/g678-admission-v1/host-v94.json',bytes:136221,
 sha256:'3aa87dbbb8fe1576efb1faae191614053e4ab5ee7d8cefb4e0a68a411dfc23cc'};
const NEXT_INDEX='catalog/g678-admission-v1/index-v96.json';
const ACTIVATION='apps/web/lib/g678-admission-activation.ts';
const RECEIPT='output/alg-l06-p028-admission-activation-v1/recovery-v1.json';
const RECOVERY='work/g678-workflow/candidates/shared-alg001-l06-p028-activation-recovery-v1';
const TARGETS=[REGISTRY,...DISPATCH,ACTIVATION];
const serialize=value=>Buffer.from(JSON.stringify(value,null,2)+'\n');
const pin=(file,bytes)=>({path:file,bytes:bytes.length,sha256:sha256(bytes)});
const activation=indexPin=>Buffer.from('// Reviewed split-proof activation. Generated by the admission build, not a page renderer.\n'+
 `export const G678_ADMISSION_INDEX = ${JSON.stringify(indexPin,null,2)} as const;\n`);
const entries=registry=>registry.calibrations.flatMap(c=>c.entries);
const shared=registry=>entries(registry).filter(e=>e.key.startsWith('shared-'));

/** No draft semantics can substitute for the promoted maintained modules. */
async function loadP028Semantics(){
 const [source,host]=await Promise.all([
  import('../lib/alg-l06-p028-admission-semantics-v1.mjs'),
  import('../lib/alg-l06-p028-host-semantics-v1.mjs')]);
 assert.deepEqual([source.ID,source.SOURCE_ROOT,source.SOURCE,source.XML,source.SA],
  [ID,SOURCE_ROOT,SOURCE,SOURCE_XML,SOURCE_SA],'promoted P028 source identity');
 assert.equal(typeof source.readP028CanonicalSource,'function','maintained source reader');
 assert.equal(typeof host.validateP028EngineeringReceipt,'function','maintained host receipt validator');
 assert.equal(typeof host.validateP028FinalPacket,'function','maintained final packet validator');
 assert.deepEqual(source.ACCEPTANCE,ACCEPTANCE,'independent acceptance gates');
 return {source,host};
}

function exactPredecessor(){
 assert.equal(process.env.HELP_MATH_G678_SOURCE_ROOT,SOURCE_ROOT,
  'physical AWS source root must be explicit');
 for(const source of [SOURCE,SOURCE_XML,SOURCE_SA])readPin(SOURCE_ROOT,source);
 assert.deepEqual(pinFile(ROOT,PRIOR_INDEX.path),PRIOR_INDEX,'exact index-v95');
 assert.deepEqual(pinFile(ROOT,PRIOR_HOST.path),PRIOR_HOST,'exact host-v94');
 const index=readJsonPin(ROOT,PRIOR_INDEX),host=verifyHostVersion(ROOT,index.host),
  transaction=readRegistryTransaction(ROOT);
 assert.deepEqual(index.host,PRIOR_HOST,'host-v94 association');
 assert.equal(index.pages.length,25,'25 predecessor proofs');
 assert(!index.pages.some(p=>p.animationId===ID),'P028 absent from predecessor index');
 assert.equal(transaction.sha256,PRIOR_REGISTRY_SHA,'exact predecessor registry');
 assert.equal(transaction.registry.calibrations.length,138,'138 predecessor calibrations');
 assert.equal(entries(transaction.registry).length,657,'657 predecessor private entries');
 assert.equal(shared(transaction.registry).length,515,'515 predecessor shared entries');
 assert(!entries(transaction.registry).some(e=>e.key===ID),'P028 absent from registry');
 assert.deepEqual(readOrdinary(ROOT,ACTIVATION),activation(PRIOR_INDEX),
  'exact predecessor activation');
 for(const page of index.pages)readPageProof(ROOT,page.proof,host,transaction);
 return {index,host,transaction};
}

/** Useful now: verifies the real predecessor and the three physical P028 files. */
export function sourceOnly(){
 const base=exactPredecessor();
 return {status:'p028-activation-predecessor-checked-not-registered',
  animationId:ID,source:SOURCE,sourceXml:SOURCE_XML,separateSpanishAudio:SOURCE_SA,
  predecessorIndex:PRIOR_INDEX,host:PRIOR_HOST,registrySha256:base.transaction.sha256,
  retainedProofs:base.index.pages.length,retainedCalibrations:138,
  retainedPrivateEntries:657,retainedSharedEntries:515,
  proofPrepared:fs.existsSync(path.join(ROOT,PROOF)),registered:false,
  registryWrites:0,indexWrites:0,activationWrites:0};
}

function validateP028Page(packet,registration,semantics){
 const canonical=semantics.source.readP028CanonicalSource(ROOT);
 const receiptPin=packet.engineeringReceipt;
 assert(receiptPin&&receiptPin.path?.startsWith('output/playwright/alg-l06-p028-'),
  'real P028 My Lesson engineering receipt');
 const receipt=readJsonPin(ROOT,receiptPin);
 // Producer/reader evidence was recorded before registration. Its historical
 // index, host, and registered=false remain true after route activation.
 assert.deepEqual([receipt.indexPin,receipt.hostPin,receipt.registered],
  [PRIOR_INDEX,PRIOR_HOST,false],
  'retain historical pre-registration engineering receipt identity');
 const engineering=semantics.host.validateP028EngineeringReceipt(receipt,ROOT,canonical);
 semantics.host.validateP028FinalPacket(packet,registration,ROOT,canonical,
  receiptPin,engineering);
}

/** Project all five successor objects in memory before any mutable write. */
export async function planActivation(){
 const base=exactPredecessor();
 assert(fs.existsSync(path.join(ROOT,PROOF)),'P028_PROOF_NOT_PREPARED');
 const semantics=await loadP028Semantics();
 const proofPin=pinFile(ROOT,PROOF),proof=readJsonPin(ROOT,proofPin);
 assert.equal(proof.animationId,ID,'one P028 proof identity');
 assert.equal(proof.registration.calibrationId,CALIBRATION,'exact P028 calibration');
 assert.deepEqual(proof.registration.entries.map(e=>e.key),[ID],
  'one P028 registration entry');
 const normalized=upsertPrivateCurrentJsCalibration(base.transaction.registry,
  proof.registration);
 const own=normalized.calibrations.find(c=>c.calibrationId===CALIBRATION);
 assert.deepEqual(own,proof.registration,'real writer produced own registration');
 // The production writer sorts calibrations. Preserve actual predecessor order.
 const byId=new Map(normalized.calibrations.map(c=>[c.calibrationId,c]));
 for(const old of base.transaction.registry.calibrations)
  assert.deepEqual(byId.get(old.calibrationId),old,'writer preserved '+old.calibrationId);
 const nextRegistry={...normalized,
  calibrations:[...base.transaction.registry.calibrations,own]};
 assert.deepEqual(nextRegistry.calibrations.slice(0,-1),
  base.transaction.registry.calibrations,'all predecessor calibrations and order');
 assert.equal(nextRegistry.calibrations.length,139,'one new calibration');
 assert.equal(entries(nextRegistry).length,658,'one new private entry');
 assert.equal(shared(nextRegistry).length,516,'one new shared entry');
 assert.deepEqual(shared(nextRegistry).filter(e=>e.key!==ID),
  shared(base.transaction.registry),'all predecessor shared entries preserved');
 const registryBytes=serialize(nextRegistry);
 const projected={registry:nextRegistry,sha256:sha256(registryBytes)};
 const packet=readPageProof(ROOT,proofPin,base.host,projected);
 validateP028Page(packet,proof.registration,semantics);
 assert.deepEqual(packet.acceptanceEffects,semantics.source.ACCEPTANCE,
  'independent acceptance gates');
 const successor={...base.index,
  pages:[...base.index.pages,{animationId:ID,proof:proofPin}]};
 assert.deepEqual(successor.pages.slice(0,-1),base.index.pages,
  'all predecessor proof pins and order');
 assert.equal(successor.pages.length,26,'one additional proof');
 const indexBytes=serialize(successor),indexPin=pin(NEXT_INDEX,indexBytes);
 const dispatch=registrySources(nextRegistry);
 const before=new Map(TARGETS.map(file=>[file,readOrdinary(ROOT,file)]));
 const after=new Map([[REGISTRY,registryBytes],
  ...DISPATCH.map((file,i)=>[file,Buffer.from(dispatch[i])]),
  [ACTIVATION,activation(indexPin)]]);
 assert.deepEqual([...before.keys()],[...after.keys()],
  'exact four replacement targets');
 return {base,semantics,proofPin,proof,packet,indexBytes,indexPin,
  nextRegistry,projected,before,after,
  summary:{beforeRegistry:pin(REGISTRY,before.get(REGISTRY)),
   afterRegistry:pin(REGISTRY,registryBytes),predecessorIndex:PRIOR_INDEX,
   successorIndex:indexPin,host:PRIOR_HOST,proof:proofPin,
   replacements:[...after].map(([file,bytes])=>pin(file,bytes)),
   preservedProofs:25,preservedCalibrations:138,preservedSharedEntries:515,
   registeredSharedEntries:516,publicFilesWritten:0,
   acceptanceEffects:semantics.source.ACCEPTANCE,
   productCalibrationPassed:false,scaleOutAuthorized:false,registered:false}};
}

function verifyInputs(plan){
 assert.deepEqual(pinFile(ROOT,PRIOR_INDEX.path),PRIOR_INDEX);
 assert.deepEqual(pinFile(ROOT,PRIOR_HOST.path),PRIOR_HOST);
 assert.deepEqual(pinFile(ROOT,PROOF),plan.proofPin,'unchanged real P028 proof');
 const host=verifyHostVersion(ROOT,PRIOR_HOST);
 for(const page of plan.base.index.pages)
  readPageProof(ROOT,page.proof,host,plan.base.transaction);
 const packet=readPageProof(ROOT,plan.proofPin,host,plan.projected);
 validateP028Page(packet,plan.proof.registration,plan.semantics);
 assert.deepEqual(packet.acceptanceEffects,plan.semantics.source.ACCEPTANCE);
 assert.deepEqual(readPin(ROOT,plan.indexPin),plan.indexBytes,
  'immutable successor index');
}

function assertCurrentTargetBytes(states){
 for(const [file,bytes] of states)
  assert.deepEqual(readOrdinary(ROOT,file),bytes,`activation target drift: ${file}`);
}

function writeImmutableIndex(plan){
 const absolute=path.join(ROOT,NEXT_INDEX);
 if(fs.existsSync(absolute))assert.deepEqual(readPin(ROOT,plan.indexPin),
  plan.indexBytes,'existing immutable successor index');
 else fs.writeFileSync(absolute,plan.indexBytes,{flag:'wx'});
 assert.deepEqual(pinFile(ROOT,NEXT_INDEX),plan.indexPin);
}

/** For review after promotion. The draft CLI deliberately cannot enter write/check. */
export async function activate({mode='--plan'}={}){
 assert(['--plan','--write','--check'].includes(mode),'P028 activation mode');
 if(mode==='--check'){
  const receipt=readJsonPin(ROOT,pinFile(ROOT,RECEIPT));
  const semantics=await loadP028Semantics();
  assert.deepEqual(receipt.acceptanceEffects,semantics.source.ACCEPTANCE);
  assert.equal(receipt.status,'local-registered-single-page-product-qa-pending');
  assert.deepEqual(receipt.predecessorIndex,PRIOR_INDEX);
  assert.deepEqual(receipt.host,PRIOR_HOST);
  assert.deepEqual(receipt.beforeRegistry,
   {path:REGISTRY,bytes:652307,sha256:PRIOR_REGISTRY_SHA});
  assert.equal(receipt.proof.path,PROOF);
  assert.deepEqual(pinFile(ROOT,PRIOR_INDEX.path),PRIOR_INDEX);
  assert.deepEqual(pinFile(ROOT,PRIOR_HOST.path),PRIOR_HOST);
  const indexPin=pinFile(ROOT,NEXT_INDEX),admitted=verifyAdmission(ROOT,indexPin);
  assert.deepEqual(indexPin,receipt.successorIndex);
  assert.equal(admitted.index.pages.length,26);
  assert.deepEqual(admitted.index.pages.slice(0,-1),
   readJsonPin(ROOT,PRIOR_INDEX).pages,'all historical proof order preserved');
  assert.deepEqual(admitted.index.pages.at(-1),
   {animationId:ID,proof:receipt.proof});
  const proof=readJsonPin(ROOT,receipt.proof);
  validateP028Page(admitted.packets[ID],proof.registration,semantics);
  const current=readRegistryTransaction(ROOT).registry;
  assert.equal(current.calibrations.length,139);
  assert.equal(entries(current).length,658);
  assert.equal(shared(current).length,516);
  assert.deepEqual(pinFile(ROOT,REGISTRY),receipt.afterRegistry);
  assert.deepEqual(receipt.replacements.map(row=>row.path),TARGETS);
  for(const expected of receipt.replacements)
   assert.deepEqual(pinFile(ROOT,expected.path),expected);
  assert.deepEqual(receipt.transaction.completed,TARGETS);
  assert.equal(receipt.transaction.rollback,false);
  assert.deepEqual(receipt.transaction.backups.map(row=>row.target),TARGETS);
  for(const backup of receipt.transaction.backups){
   assert(backup.backup.path.startsWith(`${RECOVERY}/before-`),
    'bounded immutable recovery path');
   readPin(ROOT,backup.backup);
  }
  const registryBackup=receipt.transaction.backups.find(row=>row.target===REGISTRY);
  assert.equal(registryBackup.backup.sha256,PRIOR_REGISTRY_SHA,
   'exact predecessor registry retained in recovery');
  assert.deepEqual({bytes:registryBackup.backup.bytes,
   sha256:registryBackup.backup.sha256},
  {bytes:receipt.beforeRegistry.bytes,sha256:receipt.beforeRegistry.sha256});
  const oldRegistry=JSON.parse(readPin(ROOT,registryBackup.backup).toString());
  assert.deepEqual(current.calibrations.slice(0,-1),oldRegistry.calibrations,
   'all predecessor calibrations and order retained postregistration');
  assert.deepEqual(current.calibrations.at(-1),proof.registration,
   'exact P028 registration remains last');
  return {status:'checked-local-p028-admission',index:indexPin,
   registry:receipt.afterRegistry,registeredSharedEntries:516,
   acceptanceEffects:semantics.source.ACCEPTANCE};
 }
 const plan=await planActivation();
 if(mode==='--plan')return {...plan.summary,status:'planned-not-written',
  registryWrites:0,indexWrites:0,activationWrites:0};
 assert(!fs.existsSync(path.join(ROOT,RECEIPT)),
  'P028 activation receipt already exists');
 assertCurrentTargetBytes(plan.before);
 writeImmutableIndex(plan);
 const verify=async()=>verifyInputs(plan);
 const postflight=async()=>{
  assertCurrentTargetBytes(plan.after);
  const admitted=verifyAdmission(ROOT,plan.indexPin);
  assert.equal(admitted.index.pages.length,26);
  assert.deepEqual(admitted.index.pages.at(-1),
   {animationId:ID,proof:plan.proofPin});
  validateP028Page(admitted.packets[ID],plan.proof.registration,
   plan.semantics);
  assert.equal(shared(readRegistryTransaction(ROOT).registry).length,516);
 };
 const transaction=await guardedReplacement({root:ROOT,before:plan.before,
  after:plan.after,targets:TARGETS,recovery:RECOVERY,verify,postflight});
 const receipt={schemaVersion:1,createdAt:new Date().toISOString(),
  status:'local-registered-single-page-product-qa-pending',...plan.summary,
  registered:true,transaction,
  activationTool:pinFile(ROOT,'scripts/activate-alg-l06-p028-admission-v1.mjs'),
  limitations:['Current-JS registry and local My Lesson route only; original runtime, audio listening, fidelity, human and Owner acceptance, strict completion and publication remain independent.']};
 await mkdir(path.dirname(path.join(ROOT,RECEIPT)),{recursive:true});
 await writeFile(path.join(ROOT,RECEIPT),serialize(receipt),{flag:'wx'});
 return {status:receipt.status,receipt:pinFile(ROOT,RECEIPT),
  registry:receipt.afterRegistry,index:receipt.successorIndex,
  registeredSharedEntries:516,acceptanceEffects:semantics.source.ACCEPTANCE};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 assert(process.argv.length===3&&['--source-only','--plan','--write','--check'].includes(process.argv[2]),
  'exact P028 activation modes');
 const result=process.argv[2]==='--source-only'?sourceOnly():
  await activate({mode:process.argv[2]});
 console.log(JSON.stringify(result,null,2));
}

#!/usr/bin/env node

// Product projection of the conditional P055 identified-host L1 bank candidate.
// It does not resolve the lesson XML's missing L2 banks or historical host use.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildP055ConditionalGlossary} from './prepare-nms-l02-ts-glossary.mjs';

const SCRIPT = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(SCRIPT), '..');
const CANDIDATE = 'output/nms-l02-host-successor-20260927/glossary/p055-conditional-l1-host-bank.json';
const PRODUCT = 'packages/demos/src/generated/nms-l02-p055-terms-v1.ts';
const RECEIPT = 'output/nms-l02-host-successor-20260927/glossary/p055-product-terms-receipt.json';
const CANDIDATE_SHA256 = 'cfc1e81cf4da194d2d110ccd7ca879ce43950361883319a2e6bcebd135f1543f';
const IDS = ['restate', 'question', 'problem'];
const KEYS = ['Restate', 'Question', 'Problem'];
const hash = value => createHash('sha256').update(value).digest('hex');
const jsonBytes = value => Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
const absolute = relative => path.join(ROOT, relative);

export function projectP055Product(candidate) {
  assert.equal(candidate.schemaVersion, 1);
  assert.equal(candidate.kind, 'nms-l02-p055-conditional-identified-host-l1-glossary-v1');
  assert.equal(candidate.animationId, 'shared-nms002-l02-p055');
  assert.equal(candidate.status, 'conditional-modern-host-data-candidate');
  assert.equal(candidate.sourceSelection, 'identified-indexMI-export-literal-L1-bank-path');
  assert.equal(candidate.originalL2XmlResolved, false);
  assert.equal(candidate.historicalHostAssociationEstablished, false);
  assert.equal(candidate.originalRuntimeLookupVerified, false);
  assert.deepEqual(candidate.lessonXmlDeclaredBanks, {
    en: 'HELP_KEYTERMS/KT/XML/L2KTE01.xml',
    es: 'HELP_KEYTERMS/KT/XML/L2KTS01.xml',
    recovered: false,
  });
  assert.deepEqual(candidate.terms.map(term => term.id), IDS);
  assert.deepEqual(candidate.terms.map(term => term.sourceKeyAttribute), KEYS);
  const terms = candidate.terms.map(term => {
    assert.equal(term.source.en.sha256, '14d454f4c1c1a6f0939fb80b454fd3e22890eabb4a730c6bfa7efa1d9a2e5e5b');
    assert.equal(term.source.es.sha256, '3b437b42e75536fa8b4f110325e366c27fbe10a871439d4797650cda4238b407');
    assert.deepEqual(term.matching, {
      englishHostLabelOccurrences: 1,
      spanishHostLabelOccurrences: 1,
      screenKeyTermOccurrencesPerBank: 1,
    });
    return Object.fromEntries([
      'id', 'sourceKeyAttribute', 'labels', 'definitions', 'source',
      'sourceEntrySha256', 'extractionLfNormalizedEntrySha256',
    ].map(key => [key, term[key]]));
  });
  const disposition = {
    status: candidate.status,
    sourceSelection: candidate.sourceSelection,
    candidateSha256: CANDIDATE_SHA256,
    originalL2XmlResolved: false,
    historicalHostAssociationEstablished: false,
    originalRuntimeLookupVerified: false,
  };
  return {terms, disposition};
}

export async function productBytes() {
  const candidateBytes = await readFile(absolute(CANDIDATE));
  assert.equal(hash(candidateBytes), CANDIDATE_SHA256, 'conditional source candidate SHA-256');
  const rebuilt = await buildP055ConditionalGlossary();
  assert.deepEqual(candidateBytes, jsonBytes(rebuilt), 'conditional candidate must reproduce from pinned source');
  const projection = projectP055Product(JSON.parse(candidateBytes));
  const bytes = Buffer.from(
    '// Generated by scripts/generate-nms-l02-p055-terms-v1.mjs from a conditional identified-host L1 bank candidate. Do not edit.\n' +
    '// L02 lesson XML declares unrecovered L2 banks; original host association and lookup remain unverified.\n' +
    `export const P055_GLOSSARY_SOURCE_DISPOSITION = ${JSON.stringify(projection.disposition, null, 2)} as const;\n` +
    `export const P055_SOURCE_TERMS = ${JSON.stringify(projection.terms, null, 2)} as const;\n` +
    'export type P055SourceTerm = typeof P055_SOURCE_TERMS[number];\n' +
    'export function p055SourceTerm(id: string): P055SourceTerm | undefined {\n' +
    '  return P055_SOURCE_TERMS.find(term => term.id === id);\n' +
    '}\n',
  );
  return {bytes, projection};
}

export async function generateP055Terms({check = false} = {}) {
  const {bytes, projection} = await productBytes();
  const self = await readFile(SCRIPT);
  const receipt = {
    schemaVersion: 1,
    kind: 'nms-l02-p055-conditional-product-terms-receipt-v1',
    animationId: 'shared-nms002-l02-p055',
    status: 'conditional-modern-host-data-candidate',
    sourceCandidate: {path: CANDIDATE, bytes: (await readFile(absolute(CANDIDATE))).length, sha256: CANDIDATE_SHA256},
    generator: {path: path.relative(ROOT, SCRIPT), bytes: self.length, sha256: hash(self)},
    product: {path: PRODUCT, bytes: bytes.length, sha256: hash(bytes)},
    ids: projection.terms.map(term => term.id),
    originalL2XmlResolved: false,
    historicalHostAssociationEstablished: false,
    originalRuntimeLookupVerified: false,
    registrationEffect: false,
    acceptanceEffect: false,
  };
  const receiptBytes = jsonBytes(receipt);
  if (check) {
    assert.deepEqual(await readFile(absolute(PRODUCT)), bytes, 'P055 generated product drift');
    assert.deepEqual(await readFile(absolute(RECEIPT)), receiptBytes, 'P055 product receipt drift');
  } else {
    await mkdir(path.dirname(absolute(PRODUCT)), {recursive: true});
    await mkdir(path.dirname(absolute(RECEIPT)), {recursive: true});
    await writeFile(absolute(PRODUCT), bytes, {flag: 'wx'});
    await writeFile(absolute(RECEIPT), receiptBytes, {flag: 'wx'});
  }
  return {product: receipt.product, receipt: {path: RECEIPT, bytes: receiptBytes.length, sha256: hash(receiptBytes)}, checked: check, ids: receipt.ids};
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT) {
  const arg = process.argv[2];
  assert.ok(process.argv.length === 3 && ['--prepare', '--check'].includes(arg), 'usage: generate-nms-l02-p055-terms-v1.mjs --prepare|--check');
  generateP055Terms({check: arg === '--check'})
    .then(result => process.stdout.write(`${JSON.stringify(result, null, 2)}\n`))
    .catch(error => {process.stderr.write(`${error.stack ?? error.message}\n`); process.exitCode = 1;});
}

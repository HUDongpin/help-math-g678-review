import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pin=(file,hash)=>{const b=readFileSync(path.join(root,file));assert.equal(createHash('sha256').update(b).digest('hex'),hash,file);return JSON.parse(b);};
export function buildAudioPlan(){
 const source=pin('migrations/shared-alg001-l06-p015/audit/audio-v1/audio-source-audit-v1.json','cc0613c295d148102df51dd970d391cda380ffa3ed0f4da9f77ba2c04453ae15');
 const browser=pin('output/playwright/alg-l06-p015-browser-audio-v1/decode-receipt.json','f89df97650a97f8b066519f51385067285c52b474ffc9e62d1131097946ef713');
 const entries=[];
 for(const stream of source.streams){
  for(const [index,range] of stream.contiguousRanges.entries()){
   const mp3=range.extractedMp3??stream.extractedMp3;
   const decoded=range.decode??stream.decode;
   const measured=browser.results.find(r=>r.sourceSha256===mp3.sha256);
   assert(measured);assert.equal(measured.sourceBytes,mp3.bytes);
   assert.equal(measured.decodedSamples,decoded.samples);assert.equal(measured.playbackStarted,false);
   const id=stream.domain==='sprite-270'?`main-${index+1}`:stream.domain;
   entries.push({id,domain:stream.domain,firstBlockFrame:range.firstFrame,
    lastBlockFrame:range.lastFrame,lastVisualFrame:[645,711,851,914][index],
    initialSeekSamples:range.firstPacket.rawSeekSamples,
    sourcePath:mp3.path,sourceSha256:mp3.sha256,sourceBytes:mp3.bytes,
    sampleRate:measured.sampleRate,channels:measured.channels,decodedSamples:measured.decodedSamples,
    pcmSha256:measured.pcmSha256,
    receiptSha256:'f89df97650a97f8b066519f51385067285c52b474ffc9e62d1131097946ef713',
    originalRuntimeAccepted:false,audioAccepted:false});
  }
 }
 assert.equal(entries.length,4);
 const sa=browser.results.find(r=>r.role==='separate-sa');assert(sa);
 assert.equal(sa.sourceSha256,source.separateSa.copy.sha256);
 const output='// Generated by scripts/build-alg-l06-p015-audio-plan-v1.mjs; do not hand-edit.\n'+
  'export const P015_AUDIO_ASSETS='+JSON.stringify(entries,null,2)+' as const;\n'+
  'export const P015_SA_ASSET='+JSON.stringify({...sa,sourcePath:source.separateSa.copy.path,
   receiptSha256:'f89df97650a97f8b066519f51385067285c52b474ffc9e62d1131097946ef713',
   originalRuntimeAccepted:false,audioAccepted:false},null,2)+' as const;\n';
 return output;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const mode=process.argv[2];assert(['--write','--check'].includes(mode));
 const file=path.join(root,'packages/demos/src/generated/alg-l06-p015-audio-plan-v1.ts');
 const text=buildAudioPlan();
 if(mode==='--check')assert.equal(readFileSync(file,'utf8'),text);else writeFileSync(file,text);
 console.log(`${mode} P015 four main range assets and separate SA; no playback acceptance`);
}

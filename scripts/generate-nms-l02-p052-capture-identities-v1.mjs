import fs from 'node:fs';import path from 'node:path';import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';import {createHash} from 'node:crypto';
import {canonicalJson} from './build-course-trace-specs.mjs';
import {p052CaptureState} from '../packages/demos/src/nms-l02-p052-capture-state-v1.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
assert.ok(process.argv.slice(2).every(a=>a==='--check'));
const hash=b=>createHash('sha256').update(b).digest('hex');
const read=p=>fs.readFileSync(path.join(root,p));
const bytes=read('migrations/shared-nms002-l02-p052/audit/native-main-capture-plan-v1.json');
const plan=JSON.parse(bytes);assert.equal(plan.animationId,'shared-nms002-l02-p052');
assert.equal(plan.sourceSha256,'5efa48905e74c0dd604b9e896bee1a1b4cfb1fe0839044686527fe96e1311638');
assert.equal(plan.requirements.length,160);
for(const input of plan.inputs)assert.equal(hash(read(input.file)),input.sha256,input.file);
const identities={};
for(const row of plan.requirements){
 const state=p052CaptureState({scenario:row.scenario,language:row.language,seed:row.seed,frameDomain:row.frameDomainId,frame:row.range.first});
 assert.equal(hash(canonicalJson(state.entryState)),row.entryStateSha256);
 assert.equal(row.id,`candidate-${row.scenario}-${row.language}-seed-${row.seed}`);
 assert.equal(row.originalRuntimeAuthority,'unresolved');assert.equal(row.imageCaptureCount,0);
 assert.ok(!Object.hasOwn(identities,row.id));identities[row.id]=row.entryStateSha256;
}
const output=path.join(root,'packages/demos/src/generated/nms-l02-p052-capture-identities-v1.ts');
const code=`// Generated by generate-nms-l02-p052-capture-identities-v1.mjs; do not edit.\n// Candidate partial-path identities only; no original-runtime or strict authority.\nexport const P052_CAPTURE_PLAN_SHA256=${JSON.stringify(hash(bytes))};\nexport const P052_CAPTURE_IDENTITIES=${JSON.stringify(identities,null,2)} as const;\n`;
if(fs.existsSync(output))assert.equal(fs.readFileSync(output,'utf8'),code,'Identity drift; preserve/version deliberately');
else if(process.argv.includes('--check'))throw Error('Missing identity output');
else fs.writeFileSync(output,code,{flag:'wx'});
console.log(JSON.stringify({status:'PASS',identities:Object.keys(identities).length,planSha256:hash(bytes)}));

#!/usr/bin/env node
/** Preserve the actual P023 My Lesson host and expose one P024 projection. */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';

const input=new URL('../apps/web/components/g678-alg-l06-p023-candidate-player-v1.generated.tsx',import.meta.url);
let source=fs.readFileSync(input,'utf8');
assert.equal(createHash('sha256').update(source).digest('hex'),
 'bf7082b915fbcfad6c6ba1fdf691391924f7e1e62eaa2f2a4039ee3699966c1e');
for(const [from,to] of [
 ['G678AlgL6P023CandidatePlayer','G678AlgL6P024CandidatePlayer'],
 ['33 páginas registradas y 1 candidato sin registrar de ${descriptor.pages.length};',
  '34 páginas registradas y 1 candidato sin registrar de ${descriptor.pages.length};'],
 ['33 registered pages and 1 unregistered candidate of ${descriptor.pages.length};',
  '34 registered pages and 1 unregistered candidate of ${descriptor.pages.length};'],
 ['33/${descriptor.course.activePageCount} páginas registradas y 1 candidato sin registrar en My Lesson',
  '34/${descriptor.course.activePageCount} páginas registradas y 1 candidato sin registrar en My Lesson'],
 ['33/${descriptor.course.activePageCount} registered pages and 1 unregistered candidate in My Lesson',
  '34/${descriptor.course.activePageCount} registered pages and 1 unregistered candidate in My Lesson'],
]){
 assert.equal(source.split(from).length,2,`unique generated host phrase: ${from}`);
 source=source.replace(from,to);
}
source=source.replace(source.split('\n')[0],
 '// Generated by scripts/build-alg-l06-p024-candidate-host-v1.mjs; do not edit.');
const target=new URL('../apps/web/components/g678-alg-l06-p024-candidate-player-v1.generated.tsx',import.meta.url);
assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]),'--write|--check');
if(process.argv[2]==='--write'){
 const temporary=new URL(`${target.pathname}.tmp-${process.pid}`,target);
 try{fs.writeFileSync(temporary,source,{flag:'wx'});fs.renameSync(temporary,target);}
 finally{if(fs.existsSync(temporary))fs.unlinkSync(temporary);}
}else assert.equal(fs.readFileSync(target,'utf8'),source);
console.log('P024 candidate My Lesson player verified; 34 registered + 1 unregistered candidate');

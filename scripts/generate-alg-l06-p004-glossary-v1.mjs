#!/usr/bin/env node
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import {buildP004Glossary} from './extract-alg-l06-p004-glossary-v1.mjs';
assert(process.argv.length===3&&['--write','--check'].includes(process.argv[2]));
const audit=buildP004Glossary();
const bytes=Buffer.from(JSON.stringify(audit,null,2)+'\n');
const sha=createHash('sha256').update(bytes).digest('hex');
assert.equal(sha,'0cb0789f117db00855a5be1c1123121cdd64b7eba03b2f64ddce3d7f81f999e0');
assert.deepEqual(fs.readFileSync(new URL('../migrations/shared-alg001-l06-p004/audit/source-glossary-v1.json',import.meta.url)),bytes);
const entries=audit.entries.map(({sourceKeyAttribute,canonicalDictionaryKey,labels,definitions})=>({key:sourceKeyAttribute,canonicalDictionaryKey,labels,definitions}));
const output=`// Generated by scripts/generate-alg-l06-p004-glossary-v1.mjs; do not edit.\n// Source audit SHA-256: ${sha}\nexport const P004_GLOSSARY_CONTENT = ${JSON.stringify(entries,null,2)} as const;\n`;
const target=new URL('../packages/demos/src/alg-l06-p004-glossary-content.generated.ts',import.meta.url);
if(process.argv[2]==='--write')fs.writeFileSync(target,output,{flag:'wx'});
else assert.equal(fs.readFileSync(target,'utf8'),output);
console.log(JSON.stringify({status:'verified-generated-content',entries:entries.length,sourceAuditSha256:sha}));

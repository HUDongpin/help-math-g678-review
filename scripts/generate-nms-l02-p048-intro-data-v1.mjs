import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {collectSwfTextSourceCatalog} from './lib/swf-text-source-catalog.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const audit=path.join(root,'migrations/shared-nms002-l02-p048/audit');
const bytes=fs.readFileSync(path.join(audit,'source-input.swf'));
const sha=crypto.createHash('sha256').update(bytes).digest('hex');
if(sha!=='18786203d58efb8aa54c3701e72838887d0702ff03d68819830938a252facce7')throw Error('P048_SOURCE');
const source=collectSwfTextSourceCatalog(bytes),main=source.timelines.find(t=>t.timelineId==='sprite-498');
const definitions=new Map(source.textDefinitions.map(d=>[d.characterId,d]));
const corrections=JSON.parse(fs.readFileSync(path.join(audit,'intro-decimal-teaching-correction-v1.json'),'utf8'));
if(corrections.sourceSha256!==sha||corrections.corrections.length!==8)throw Error('P048_CORRECTIONS');
const corrected=new Map(corrections.corrections.map(r=>[r.frame,r]));
const selected=new Set([159,163,165,169,177,182,168,174,175,178,170,171,172,173,180,407,408,409,412]);
const state=new Map(),frames=[];
for(let frame=1;frame<=329;frame++){
 for(const event of main.events.filter(e=>e.frame===frame)){
  if(event.kind==='remove')state.delete(event.depth);
  if(event.kind==='place'){
   const prior=event.move?state.get(event.depth):{};
   if(event.move&&!prior)throw Error('P048_MISSING_PRIOR');
   state.set(event.depth,{...prior,...(event.characterId!==undefined?{id:event.characterId}:{}),...(event.matrix?{matrix:event.matrix}:{}),...(event.colorTransform?{colorTransform:event.colorTransform}:{})});
  }
 }
 const objects=[...state].filter(([depth,s])=>selected.has(s.id)).map(([depth,s])=>({depth,characterId:s.id,matrix:s.matrix??[1,0,0,1,0,0],alpha:(s.colorTransform?.multiply?.[3]??256)/256}));
 let sourceHundredths=null,hundredths=null;
 if(frame>=84){
  const digits=[state.get(20),state.get(21)].map(s=>definitions.get(s?.id)?.initialText?.text);
  if(!digits.every(s=>/^\d$/.test(s??'')))throw Error('P048_DIGITS');
  sourceHundredths=Number(digits.join(''));hundredths=sourceHundredths;
  if(corrected.has(frame)){const correction=corrected.get(frame);if(correction.sourceHundredths!==sourceHundredths)throw Error('P048_CORRECTION_DRIFT');hundredths=correction.nativeHundredths;}
 }
 frames.push({frame,sourceHundredths,hundredths,objects});
}
const ranges=[];
for(const row of frames){const {frame,...value}=row;const previous=ranges.at(-1);if(previous&&JSON.stringify(previous.value)===JSON.stringify(value))previous.last=frame;else ranges.push({first:frame,last:frame,value});}
const output='// Generated by scripts/generate-nms-l02-p048-intro-data-v1.mjs; do not edit.\nexport const P048_INTRO_RANGES = '+JSON.stringify(ranges)+' as const;\n';
const target=path.join(root,'packages/demos/src/generated/nms-l02-p048-intro-data-v1.ts');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==output)throw Error('P048_GENERATED_DRIFT');}else fs.writeFileSync(target,output);
console.log(JSON.stringify({sourceSha256:sha,frames:frames.length,ranges:ranges.length,corrections:corrected.size,scope:'Selected source intro objects and numeric values only; not complete page semantic/visual coverage.'}));

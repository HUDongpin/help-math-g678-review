import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
const input=new URL('../apps/web/components/g678-multi-page-lesson-player-v5.generated.tsx',import.meta.url);
let source=fs.readFileSync(input,'utf8');
assert.equal(createHash('sha256').update(source).digest('hex'),'8667bc039fed49a01ab949768a32648070fd58ba2ad664133aeb4a73862c0525');
for(const [from,to] of [
 ['G678MultiPageLessonPlayer','G678AlgL6P004FormalPlayer'],
 ["{spanish ? 'Cerrar y continuar' : 'Close and continue'}","{spanish ? 'Cerrar glosario' : 'Close glossary'}"],
]){assert.equal(source.split(from).length,2);source=source.replace(from,to);}
source=source.replace(source.split('\n')[0],'// Generated by scripts/generate-alg-l06-p004-formal-player-v1.mjs; do not edit.');
const target=new URL('../apps/web/components/g678-alg-l06-p004-formal-player-v1.generated.tsx',import.meta.url);
assert(['--write','--check'].includes(process.argv[2]));
if(process.argv[2]==='--write')fs.writeFileSync(target,source);else assert.equal(fs.readFileSync(target,'utf8'),source);
console.log('P004 formal player verified; registration counts come from the verified descriptor');

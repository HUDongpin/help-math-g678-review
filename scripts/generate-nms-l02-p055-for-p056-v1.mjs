function replaceExactlyOnce(source,before,after,where){
  const start=source.indexOf(before);
  assert.ok(start>=0,`P055 transform input absent: ${where}: ${before}`);
  assert.equal(source.indexOf(before,start+before.length),-1,`P055 transform input duplicated: ${where}: ${before}`);
  assert.equal(source.indexOf(after),-1,`P055 transform output already present: ${where}: ${after}`);
  return source.slice(0,start)+after+source.slice(start+before.length);
}

/** The generated byte sequence differs from each frozen source only by its listed replacements. */
export async function buildP055ForP056Files(){
  const result=[];
  for(const spec of COPY){
    const sourceBytes=await readFile(path.join(ROOT,spec.source));
    assert.equal(sha(sourceBytes),spec.sourceSha256,`Frozen P055 input changed: ${spec.source}`);
    let value=sourceBytes.toString('utf8');
    assert.deepEqual(Buffer.from(value,'utf8'),sourceBytes,`P055 input is not canonical UTF-8: ${spec.source}`);
    for(const [before,after] of spec.replacements)value=replaceExactlyOnce(value,before,after,spec.source);
    const outputBytes=Buffer.from(value,'utf8');
    result.push(Object.freeze({source:spec.source,sourceSha256:spec.sourceSha256,
      output:spec.output,bytes:outputBytes,sha256:sha(outputBytes),
      replacements:spec.replacements.map(([from,to])=>Object.freeze({from,to}))}));
  }
  return Object.freeze(result);
}

export async function generateP055ForP056(mode){
  assert.ok(mode==='--write'||mode==='--check'||mode==='--dry-run',
    'Use --dry-run, --write, or --check');
  const files=await buildP055ForP056Files();
  for(const file of files){
    const target=path.join(ROOT,file.output);
    if(mode==='--write')await writeFile(target,file.bytes,{flag:'wx'});
    if(mode==='--check')assert.deepEqual(await readFile(target),file.bytes,
      `Generated P055 predecessor drift: ${file.output}`);
  }
  return Object.freeze({kind:'nms-l02-p055-for-p056-exact-transform-v1',mode,
    predecessorAssetNamespace:'/migration-assets/nms-l02-p056-predecessors/',
    nativeRuntimeSha256:RUNTIME_SHA,mainAudioSha256:AUDIO_SHA,
    files:files.map(({source,sourceSha256,output,bytes,sha256,replacements})=>({
      source,sourceSha256,output,bytes:bytes.length,sha256,replacements})),
    acceptanceEffects:{p055SourceChanged:false,p055RegistrationChanged:false,
      p056Registered:false,originalRuntimeAccepted:false,audioAccepted:false}});
}

